def main():
    chain = build_provider_chain()
    if not chain:
        print("[error] 沒有任何可用的 LLM 供應商（需要 GEMINI_API_KEY / GITHUB_TOKEN / GROQ_API_KEY 其中之一）")
        sys.exit(1)
    for p in chain:
        print(f"[provider] {p['name']}：{' → '.join(p['models'])}")
    print(f"[geo] 查座標主要服務：{'Google' if GOOGLE_ENABLED else 'OpenStreetMap（未設定 GOOGLE_GEOCODING_KEY）'}")

    previous = load_previous()
    print(f"[db] 既有活動 {len(previous)} 筆")

    new_events = []
    for source in SOURCES:
        print(f"[source] {source['name']}")
        page_url = source["url"]
        if source.get("follow") == "pokemon_calendar":
            found = resolve_pokemon_calendar(page_url)
            if found:
                FOLLOWED_URLS.add(found)
                print(f"  [follow] 當月行事曆 → {found[len(POKEMON_SHOP_HOST):]}")
                page_url = found
            else:
                # 沒有行事曆是正常的（該店這個月沒排活動），但版面改了也長這樣。
                # 退回清單頁：拿不到內容最多是 0 筆，不會比現在更差。
                print("  [warn] 找不到當月行事曆連結，改用活動清單頁")
        page_text = fetch_page_text(page_url, source.get("locale"),
                                    source.get("nocache", False))
        if page_text is None:
            print("  [fail] 抓取失敗，跳過（既有資料由合併機制保留）")
            continue
        print(f"  [page] {len(page_text)} 字")
        DROP_REASONS.clear()   # ⚠️ 逐來源歸零，否則印出來的是累計值（看起來每個來源都在丟）
        raw_events = llm_extract(chain, build_prompt(page_text, source))
        cleaned = [e for e in (clean_event(r, source) for r in raw_events) if e]
        if not cleaned:
            # 見 future_date_count 上方那段：把「這頁沒活動」與「抽取壞了」分開。
            n_future = future_date_count(page_text)
            if n_future >= SILENT_ZERO_DATES:
                bump("silent_zero")
                print(f"  [warn] 這一頁有 {n_future} 個未來日期，卻抽取 0 筆 ← 疑似靜默歸零")
                # ⚠️ 再往下切一刀：0 筆是「模型回空」還是「模型有回而我們全丟了」。
                # 兩者的修法相反（前者要重問，後者要改 prompt 或規則），而在這行之前
                # 它們長得一模一樣。見 drop() 上方那段。
                if not raw_events:
                    print("  [zero] 模型回空陣列 ← 不是被過濾掉的")
                else:
                    print(f"  [zero] 模型回 {len(raw_events)} 筆，全數被過濾：{drop_summary()}")
        elif DROP_REASONS:
            # 有抽到東西但也丟了一些：可能是正常的（列表頁混著已結束的活動），
            # 也可能是漏抓。先讓它可見，不做任何判斷。
            print(f"  [drop] 另丟棄 {sum(DROP_REASONS.values())} 筆：{drop_summary()}")
        print(f"  [ok] 抽取 {len(cleaned)} 筆")
        new_events.extend(cleaned)
        time.sleep(SOURCE_WAIT)

    merged = merge_events(new_events, previous)
    fresh = stamp_first_seen(merged, previous)
    # 獨立一行印出，**刻意不併進 [done]**：公開 repo 的摘要是拿文案字串 grep 的，
    # 改動既有那幾行會讓摘要靜默少一行（地雷 #19）。新增的行只進 run.log，安全。
    print(f"[new] 今天首次收錄 {fresh} 筆")

    verify_images(merged, previous)

    # ⚠️ **`geo_rv` 跟著座標一起沿用**（單位 T-4）：座標沒變，之前那次反查複驗的結果
    # 就仍然有效。少了它，每天重新抽到的活動都會變成「沒驗過」而塞滿複驗佇列
    # ——**而那些的座標其實是沿用的、早就驗過了**，於是真正沒驗過的永遠排不到。
    prev_coords = {
        ev["id"]: (ev.get("lat"), ev.get("lng"), ev.get("geo"), ev.get("geo_rv"))
        for ev in previous if can_reuse_coords(ev)
    }
    prev_by_id = {ev["id"]: ev for ev in previous if ev.get("id")}
    geo_new, geo_redo, geo_strict = 0, 0, 0
    for ev in merged:
        cached = prev_coords.get(ev.get("id"))
        if cached and cached[0]:
            ev["lat"], ev["lng"], ev["geo"] = cached[0], cached[1], cached[2]
            ev["geo_v"] = GEO_VERSION
            if cached[3]:
                ev["geo_rv"] = cached[3]
            ev.pop("ai_lat", None)
            ev.pop("ai_lng", None)
        else:
            # 重查時把先前的紀錄傳進去當保底，確保結果只會變好不會變差。
            # 唯一的例外是判定改嚴而要重驗的那幾筆——它們的舊座標正是不可信的那個，
            # 保底會讓重驗完全失效（見 resolve_coords 的 trust_previous）。
            prev_rec = prev_by_id.get(ev.get("id"))
            strict = bool(prev_rec) and needs_strict_recheck(prev_rec)
            resolve_coords(ev, prev_rec, trust_previous=not strict)
            geo_new += 1
            if prev_rec:
                geo_redo += 1
            if strict:
                geo_strict += 1

    # 反查複驗（單位 T-4）：座標都定案之後才驗，因為要驗的是「最終要寫出去的那一份」
    # ——沿用的與重查的都在裡面。放在寫檔之前，降級才會落地。
    reverify_coords(merged)

    added = len(merged) - sum(
        1 for ev in previous
        if valid_date(ev.get("date_end")) and valid_date(ev["date_end"]) >= TODAY
    )

    output = {
        "schema_version": SCHEMA_VERSION,
        "updated_at": datetime.now(JST).strftime("%Y-%m-%d %H:%M"),
        "count": len(merged),
        "events": merged,
    }
    with open(OUTPUT_FILE, "w", encoding="utf-8") as f:
        json.dump(output, f, ensure_ascii=False, indent=1)

    print_report(merged, geo_new, geo_redo, geo_strict)
    print(f"[done] 本次新增約 {max(added, 0)} 筆，資料庫共 {len(merged)} 筆 → events.json")


def print_report(merged, geo_new, geo_redo=0, geo_strict=0):
    """執行結果統計。手動觸發後主要靠這幾行判斷改動有沒有生效。"""
    def tally(keys, labels):
        return " / ".join(f"{lab} {GEO_STATS.get(k, 0)}" for k, lab in zip(keys, labels))

    print(f"[stats] 模型使用：{USAGE_STATS or '無成功呼叫'}")
    # ⚠️ **刻意用 `[warn]` 前綴而不是 `[stats]`**：公開 repo 的摘要是拿文案字串 grep 的
