def parse_latlng(raw, area=""):
    """
    讀取 AI 給的經緯度，通過兩道才採信，否則回傳 None：
      ① 在 GEO_BBOX 內（2026-08-28 起是整個日本，只當地板用）
      ② 離該活動地區桶的中心不超過 `ai_max_km(area)`（**逐桶**，見該表）

    ⚠️ **第二道是框放大之後的替代品，不是額外的保險。** 框本身已經擋不住
    「大阪的活動配到東京的座標」這種事了（兩者都在日本），而那正是幻覺最常見的長相。
    ⚠️ 框本身**擋不掉鄰國**也是事實：任何一個涵蓋与那国到根室的矩形都會包含首爾與
    海參崴（實測首爾 37.57N/126.98E 落在框內），經緯度矩形做不到這件事。
    真正在擋的是這道距離守門。
    """
    try:
        lat = float(raw.get("lat", 0) or 0)
        lng = float(raw.get("lng", 0) or 0)
    except (TypeError, ValueError):
        return None
    lat_min, lng_min, lat_max, lng_max = GEO_BBOX
    if not (lat_min <= lat <= lat_max and lng_min <= lng <= lng_max):
        return None
    center = AREA_CENTER.get(area)
    if center and haversine_km((lat, lng), center) > ai_max_km(area):
        bump("ai_far_rejected")
        return None
    return (round(lat, 6), round(lng, 6))


def venue_out_of_scope(ev):
    """場地名是否指向抓取範圍外的市町村（見 OUT_OF_SCOPE_VENUE 的說明）"""
    v = (ev.get("venue_ja") or "") + " " + (ev.get("venue") or "")
    return any(k in v for k in OUT_OF_SCOPE_VENUE)


# ⚠️ 「抽取 0 筆」同時代表三件事：模型回空陣列／模型有回但這裡全部丟掉／這頁真的沒活動。
# 三者擠在同一個數字裡，那個數字就失去警告能力（同「範圍外 vs 地址不完整」那條），
# 而 clean_event 的六條丟棄路徑裡原本只有一條留下紀錄，其餘五條完全靜默。
# 故每條路徑都經由 drop() 回 None，把原因記下來：
#   DROP_REASONS 是「這一個來源」的（main() 每個來源開始前清空）
#   DROP_TOTAL   是整輪累計，收尾印一行
# ⚠️ 這一段只記錄、不改變任何判斷——階段 1 的目的是讓 0 筆分得出堆，不是修它。
DROP_REASONS = {}
DROP_TOTAL = {}


def drop(reason):
    """記下這一筆是被哪一條規則丟掉的，並回 None（維持 clean_event 原本的合約）"""
    DROP_REASONS[reason] = DROP_REASONS.get(reason, 0) + 1
    DROP_TOTAL[reason] = DROP_TOTAL.get(reason, 0) + 1
    return None


def drop_summary(counter=None):
    """把丟棄原因排成一行，筆數多的排前面"""
    c = DROP_REASONS if counter is None else counter
    return "、".join(f"{k} {v}" for k, v in sorted(c.items(), key=lambda kv: (-kv[1], kv[0])))


# ⚠️ 標題尾端那截「整個就是日期」的括號要剝掉（2026-09-12，單位 O-3 的八王子那一件）。
# `八王子觀光` 那一頁把日期寫進標題本身，於是抽出來的 `title_ja` 長這樣：
#   `八王子大江戸舞祭2026（９月１３日）`／`第４７回八王子いちょう祭り（１１月２１日・２２日）`
# 日期本來就有自己的欄位，留在標題裡是重複資訊，而且卡片上會多出一截括號。
# ⚠️ **這個毛病只有日文標題有**：實測那 18 筆的繁中 `title` 一個都沒夾日期——
# 模型翻譯時自己就拿掉了，照抄原文的規則才讓它留在 `title_ja` 裡。
# 也就是說**切到中文完全正常，只有日文使用者看得到**（同「兩個下拉都叫エリア」那一族）。
# ⚠️ 刻意不改 prompt：那是全站 138 個來源共用的，為一個來源的版面去動它，
# 影響面大、而且要等下一輪才知道模型聽不聽話。這一截是確定性的版面雜訊，
# 程式剝得乾淨也當場驗得出來（同 `simplify_venue()` 在程式端處理場地名附註的先例）。
#
# 三條規則，方向一律是**寧可漏剝也不要誤剝**：
#   ① **括號內必須同時出現「月」與「日」**。只有「月」的一律不剝，那是**場次**不是雜訊——
#      ⚠️⚠️ 這一道是**全站掃描救回來的**：Walker+ 那四個跳蚤市場來源有 78 個欄位長成
#      `東本願寺前 お東さんフリーマーケット（9月）`／`（10月）`／`（11月）`／`（12月）`，
#      同一個市集每月辦一次、**括號裡那個月份正是用來區分場次的**。剝掉之後四張卡片的
#      標題會一模一樣，而 `id` 靠 `date_start` 仍然不同＝**不撞號、不報錯，
#      只是畫面上分不出哪一張是哪個月**。八王子那 13 筆則全部帶「日」。
#      📌 只驗目標來源的話這件事看不見（八王子那 13 筆本來就全過）。
#   ② **只認阿拉伯數字（全形半形都收），不認漢數字**：漢數字在活動名稱裡太常見
#      （`第十回`／`三社祭`），認了會誤剝。同 `title_too_coarse()` 拒絕漢數字的理由。
#   ③ **只剝尾端那一組**，錨在字串結尾。中間的括號是名稱本體的一部分。
# 實測的陷阱是 `第2回 ジン八祭 （じんやさい）`——括號裡是**讀音不是日期**，
# 靠字元集把假名擋在外面。巢狀的 `（９月１３日（土））` 也不剝（字元集不含左括號）。
_TITLE_DATE_TAIL_RE = re.compile(
    r"\s*[（(]"
    r"(?=[^）)]*月)"                                            # ① 括號內要同時有「月」
    r"(?=[^）)]*日)"                                            #    與「日」（只有月＝場次）
    r"[0-9０-９月日\s\u3000~～〜\-－ー–—・、，,/／]+"              # ② 只有數字與日期分隔符
    r"[）)]\s*$"                                               # ③ 錨在尾端
)


def strip_date_tail(name):
    """剝掉標題尾端那組「整個就是日期」的括號（見上方說明）"""
    if not name:
        return name
    out = _TITLE_DATE_TAIL_RE.sub("", name).strip()
    # 剝完變空字串代表這個標題整個就是一組日期，那寧可維持原樣（剝掉等於沒有標題）
    return out or name


def clean_event(raw, source):
    """驗證與正規化單筆活動，不合格回傳 None"""
    title = str(raw.get("title", "")).strip()
    if not title:
        return drop("標題空")
    d_start = valid_date(raw.get("date_start"))
    if d_start is None:
        return drop("日期不合格")
    d_end = valid_date(raw.get("date_end")) or d_start
    if d_end < d_start:
        d_start, d_end = d_end, d_start
    if d_end < TODAY:
        return drop("日期已過")
    area = str(raw.get("area", "")).strip()
    if area not in AREAS:
        # 不在白名單內＝AI 抓了範圍外的活動，直接丟棄（見 AREAS 的說明）
        return drop("地區不在白名單")
    venue = str(raw.get("venue", "")).strip()[:50]
    venue_ja = str(raw.get("venue_ja", "")).strip()[:50]
    if venue_out_of_scope({"venue": venue, "venue_ja": venue_ja}):
        bump("dropped_out_of_scope")
        # 地區值合法但場地明顯在範圍外（見 OUT_OF_SCOPE_VENUE 的說明）
        return drop("場地在範圍外")
    raw_type = str(raw.get("type", "")).strip()
    if raw_type in TYPES:
        ev_type = raw_type
    elif source["type"] in TYPES:
        ev_type = source["type"]
    else:
        # 自動分類來源但 AI 給了無效類型，捨棄
        return drop("分類不在七類內")
    url = str(raw.get("url", "")).strip()
    if not url.startswith("http"):
        url = source["url"]
    img = clean_img_url(str(raw.get("img", "")).strip())
    ai_ll = parse_latlng(raw, area)   # ⚠️ 一定要把 area 傳進去，那是距離守門的依據
    ev = {
        # ⚠️ 兩個欄位都套同一條規則（繁中目前一筆都沒命中，但規則一致才不必記例外）。
        # ⚠️ 一定要在 `id_base` 之前剝——號碼是拿 `title_ja` 算的。
        "title": strip_date_tail(title)[:80],
        "title_ja": strip_date_tail(str(raw.get("title_ja", "")).strip())[:80],
        "type": ev_type,
        "date_start": d_start.isoformat(),
        "date_end": d_end.isoformat(),
        "area": area,
        "venue": venue,
        "venue_ja": venue_ja,
        "desc": str(raw.get("desc", "")).strip()[:60],
        "desc_ja": str(raw.get("desc_ja", "")).strip()[:60],
        "url": url,
        "img": img,
        "source": source["name"],
        "ai_lat": ai_ll[0] if ai_ll else 0,   # 暫存 AI 座標，稍後與查到的座標交叉比對
        "ai_lng": ai_ll[1] if ai_ll else 0,
    }
    # 身分證號以日文標題為準：日文是照抄原文的，不像繁中譯名每次可能不同，
    # 可大幅減少「同一活動因譯名飄移而重複收錄」。抽不到日文時退回繁中。
    id_base = ev["title_ja"] or ev["title"]
    ev["id"] = hashlib.md5((id_base + "|" + ev["date_start"]).encode("utf-8")).hexdigest()[:12]
    return ev


