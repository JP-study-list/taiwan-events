KANAGAWA_BUCKETS = {"橫濱", "川崎", "鎌倉湘南", "箱根熱海"}


def area_options(source):
    """
    這個來源可能出現的地區桶。SOURCES 沒填 areas（或填 None）代表全國性來源，給全部選項。

    **標註要寧寬勿窄。** 選項少確實能提高分類準確度，但萬一來源真的出現了鄰縣的活動，
    AI 手上沒有正確選項時，可能把它硬塞進「最接近的那個桶」——那比多給幾個選項更糟，
    因為 clean_event 的白名單擋不住一個「合法但錯誤」的值。故只有地區明確的官方觀光
    網站與按縣分頁的 Walker+ 才給窄標註，綜合性／全國性來源一律不限制。
    """
    picked = source.get("areas")
    names = [a for a in (picked or AREAS) if a in AREA_SPEC]
    return names or list(AREAS)


