def call_gemini(model, prompt):
    data = http_post_json(
        f"https://generativelanguage.googleapis.com/v1beta/models/{model}:generateContent?key={GEMINI_API_KEY}",
        {
            "contents": [{"parts": [{"text": prompt}]}],
            "generationConfig": {"temperature": 0.1, "responseMimeType": "application/json"},
        },
        {},
    )
    return data["candidates"][0]["content"]["parts"][0]["text"]


def call_openai_compat(endpoint, key, model, prompt):
    data = http_post_json(
        endpoint,
        {
            "model": model,
            "messages": [{"role": "user", "content": prompt}],
            "temperature": 0.1,
            "max_tokens": 16000,   # 雙語欄位使輸出加倍，8000 會截斷成不合法 JSON
        },
        {"Authorization": "Bearer " + key},
    )
    return data["choices"][0]["message"]["content"]


def call_github(model, prompt):
    return call_openai_compat(
        "https://models.github.ai/inference/chat/completions", GITHUB_TOKEN, model, prompt
    )


def call_groq(model, prompt):
    return call_openai_compat(
        "https://api.groq.com/openai/v1/chat/completions", GROQ_API_KEY, model, prompt
    )


def detect_gemini_models():
    """查詢 key 可用的 Gemini 模型，回傳依偏好排序的候選清單"""
    try:
        raw = http_get(
            "https://generativelanguage.googleapis.com/v1beta/models?key=" + GEMINI_API_KEY
        )
        models = json.loads(raw).get("models", [])
        available = set()
        for m in models:
            if "generateContent" in m.get("supportedGenerationMethods", []):
                available.add(m.get("name", "").replace("models/", ""))
        ordered = [p for p in GEMINI_MODEL_PREFS if p in available]
        extras = sorted(
            [m for m in available
             if "flash" in m
             and not any(x in m for x in ("image", "live", "tts", "omni", "audio"))
             and m not in ordered],
            reverse=True,
        )
        return ordered + extras
    except (urllib.error.URLError, urllib.error.HTTPError, OSError, json.JSONDecodeError) as e:
        print(f"[warn] Gemini 模型清單查詢失敗：{e}")
        return []


def build_provider_chain():
    """依可用憑證組出供應商鏈"""
    chain = []
    if GEMINI_API_KEY:
        gm = detect_gemini_models()
        if gm:
            chain.append({"name": "gemini", "models": gm, "call": call_gemini})
    if GITHUB_TOKEN:
        chain.append({"name": "github", "models": GITHUB_MODELS, "call": call_github})
    if GROQ_API_KEY:
        chain.append({"name": "groq", "models": GROQ_MODELS, "call": call_groq})
    return chain


def parse_events_text(text):
    """LLM 回應文字 -> list，失敗拋 ValueError"""
    cleaned = re.sub(r"^```(json)?|```$", "", text.strip(), flags=re.MULTILINE).strip()
    events = json.loads(cleaned)
    if not isinstance(events, list):
        raise ValueError("回傳非陣列")
    # ⚠️ 只檢查「是不是陣列」不夠：模型偶爾回**字串陣列**，clean_event 拿到 str
    # 呼叫 .get() 會當場 AttributeError，而 main() 的來源迴圈沒有 try ——
    # 2026-08-28 的排程就是這樣整支中止、events.json 一整天沒更新（第一百三十七筆）。
    # ⚠️ 濾掉之後一定要印一行：這是「模型回了沒見過的形狀」，屬於該被看見的事，
    # 不可比照 clean_event 那種「不合格就靜默回 None」的合約。
    good = [e for e in events if isinstance(e, dict)]
    if len(good) != len(events):
        print(f"  [warn] 回傳陣列裡有 {len(events) - len(good)} 個非物件元素，已丟棄")
    return good


def llm_extract(chain, prompt):
    """
    依供應商鏈逐一嘗試抽取。
    淘汰規則：404（模型不存在）立即淘汰不重試；429 重試 RETRY 次後淘汰；
    其他錯誤重試後換下一個模型但不淘汰（下個來源仍可再試）。
    """
    for provider in chain:
        for model in provider["models"]:
            key = provider["name"] + ":" + model
            if key in DEAD_MODELS:
                continue
            quota_fails = 0
            for attempt in range(RETRY):
                try:
                    events = parse_events_text(provider["call"](model, prompt))
                    USAGE_STATS[key] = USAGE_STATS.get(key, 0) + 1
                    return events
                except urllib.error.HTTPError as e:
                    print(f"  [warn] {key} HTTP {e.code}（{attempt + 1}/{RETRY}）")
                    if e.code in (404, 400, 401, 403):
                        DEAD_MODELS.add(key)
                        print(f"  [info] {key} 不可用（{e.code}），換下一個模型")
                        break
                    if e.code == 429:
                        quota_fails += 1
                except (json.JSONDecodeError, ValueError, KeyError, IndexError) as e:
                    print(f"  [warn] {key} 回應解析失敗（{attempt + 1}/{RETRY}）：{e}")
                except (urllib.error.URLError, OSError) as e:
                    print(f"  [warn] {key} 連線失敗（{attempt + 1}/{RETRY}）：{e}")
                if attempt < RETRY - 1:
                    time.sleep(RETRY_WAIT)
            if key in DEAD_MODELS:
                continue
            if quota_fails >= RETRY:
                DEAD_MODELS.add(key)
                print(f"  [info] {key} 配額耗盡，換下一個模型")
            # 其他失敗：換下一個模型，但保留資格
    return []


