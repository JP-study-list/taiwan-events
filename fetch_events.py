# 死連結的兩種樣態：
#   1. 來源站正確回傳 404／410，由 Jina 標記在開頭——網址真的失效，重試無用
#   2. 軟性 404——來源站回傳 HTTP 200，但內容其實是「找不到頁面」。日文網站很常見，
#      Jina 不會標記，只能從標題辨識。
#
# **不是死連結的第三種：來源站回 429／403／5xx。** 那只是被限速或暫時故障，網址仍有效，
# 而且 Jina 這時往往還是拿得到內容（2026-08-05 實測高崎觀光回 429，內容仍有 14,325 字、
# 17 個日期，完全可用）。舊版把所有 `Warning: Target URL returned error` 一律當死連結，
# 於是白白丟掉一個來源，日誌還誤報成「網址可能已失效」，害人跑去換網址——但網址沒問題。
# 來源愈多愈容易被日本網站限速，故必須把「永久失效」與「暫時被擋」分開。
# **一律小寫比對**：實測群馬縣立近代美術館的 404 頁標題是「Page not found」，
# 與清單裡的「Page Not Found」只差大小寫就漏掉了。日文不受 lower() 影響。
# 「404エラー」是日光旅ナビ的 404 頁標題，同樣曾經漏掉。
# 這兩個漏洞在 2026-08-05 拿 6 個真實 404 頁實測時才浮現——**新增來源時請順手打一個
# 不存在的路徑，看它的 404 頁標題有沒有落在本清單裡**，否則該來源哪天搬家就會靜默歸零。
# 「404 notfound」（**沒有空格**）是大阪觀光局 osaka-info.jp 的 404 頁標題，2026-08-28
# 開通關西實測時抓到——與清單裡的「404 not found」**只差一個空格就比不中**，
# 與上面群馬那個「只差大小寫」是同一種漏法。**這份清單是逐字比對，不做任何正規化，
# 所以同一個意思的每一種寫法都要各列一行。**
#
# ⚠️⚠️ **「not found」（光禿禿的）是 2026-09-04 接第二批新桶時補的，而它與上面每一條
# 都不同：前面那些是「多一種寫法」，這一條是「把前面兩條包進去的上位詞」。**
# 起因是熊本縣觀光網 kumamoto.guide 的 404 頁標題是
