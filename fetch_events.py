def normalize_venue(name):
    """
    產生「同一個名字的另一種寫法」，回傳空字串代表沒有可正規化之處。

    **根因是 OSM 與來源網站的寫法不一致，不是資料缺失**（地雷 #3d）：
      「SHIBUYA109」    → OSM 收的是「Shibuya 109」／name:ja「SHIBUYA 109」（中間有空白）
      「ＣＲＥＶＩＡ…」  → 全形在 name_confidence 只判得到 weak，半形才是 strong
      「唐澤山神社」     → OSM 收「唐沢山神社」

    三種處理都只是換個寫法，語意完全相同，所以放在原名之後、簡化之前試——
    比 simplify_venue（會砍掉字）保守。查錯了就是查無，退回原本的流程。
    """
    s = []
    for c in name:
        o = ord(c)
        if 0xFF21 <= o <= 0xFF3A or 0xFF41 <= o <= 0xFF5A or 0xFF10 <= o <= 0xFF19:
            s.append(chr(o - 0xFEE0))      # 全形英數 → 半形
        elif o == 0x3000:
            s.append(" ")                  # 全形空白 → 半形
        else:
            s.append(VARIANT_KANJI.get(c, c))
    out = "".join(s)
    # 日文與英數之間、英文字母與數字之間補空白。**只補不刪**——刪空白會把
    # 「CHANEL NEXUS HALL」這種本來就分寫的名稱黏成一團，反而查不到。
    out = re.sub(rf"([{_JA_CHARS}])([A-Za-z0-9])", r"\1 \2", out)
    out = re.sub(rf"([A-Za-z0-9])([{_JA_CHARS}])", r"\1 \2", out)
    out = re.sub(r"([A-Za-z])([0-9])", r"\1 \2", out)
    out = re.sub(r"[\s]+", " ", out).strip()
    return "" if out == name else out


def simplify_venue(name):
    """
    產生查詢用的簡化場地名。回傳空字串代表沒有可簡化之處，呼叫端應略過該段查詢。
      「パシフィコ横浜 展示ホールA」    → 「パシフィコ横浜」
      「横浜ベイクォーター3F メイン広場」→ 「横浜ベイクォーター」
      「EKIMISE（エキミセ）」          → 「EKIMISE」
    注意：只在「広場／会場／ホール」前面有空白時才剝，避免把「さくら広場」這種
    名稱本體的一部分砍掉。
    """
    s = name
    for pat in VENUE_TRIM:
        s = pat.sub("", s)
    s = re.sub(r"[\s　]+", " ", s).strip(" 　・、,")
    if len(s) < 2 or s == name:
        return ""
    return s


