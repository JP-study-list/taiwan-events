def load_previous():
    """
    讀取既有資料庫。三種情況必須分開處理，不可混為一談：
      檔案不存在 → 合法的首次執行，回空陣列
      版本不符   → 改版，刻意整批汰換重建
      檔案損毀   → 中止執行。若靜默當成空的，累積多日的資料會被無聲清空且無人察覺
    """
    if not os.path.exists(OUTPUT_FILE):
        print("[db] events.json 不存在，視為首次執行")
        return []
    try:
        with open(OUTPUT_FILE, "r", encoding="utf-8") as f:
            data = json.load(f)
    except (OSError, json.JSONDecodeError) as e:
        print(f"[error] events.json 存在但無法讀取／解析：{e}")
        print("[error] 為避免靜默清空既有資料，本次執行中止。請檢查檔案或用 git 還原。")
        sys.exit(1)

    version = data.get("schema_version", 1)
    events = data.get("events", [])
    if version != SCHEMA_VERSION:
        print(f"[db] 資料格式 v{version} → v{SCHEMA_VERSION}，既有 {len(events)} 筆不相容，整批汰換重建")
        return []
    return events


def url_dedup_key(ev, src_urls):
    """
    活動專屬詳情頁網址。退回來源列表頁時回 None——那個網址整批共用，
    拿來當鍵會把同一來源的活動全部誤判成同一筆。
    """
    url = (ev.get("url") or "").strip()
    return url if url and url not in src_urls else None


def inherit_ids(new_events, previous_events, src_urls):
    """
    詳情頁網址對得上時，沿用既有活動最早發下去的 id。

    id 是 md5(日文標題 + 開始日)，而這兩者每天都會被 LLM 重新解讀——實測
    08-01 → 08-02 有 14 筆（3.9%）同一活動換了 id。使用者收藏（localStorage
    存的是 id）與日後的行程分享連結都指向 id，id 一變就默默失效、活動卻還在。

    故 id 的定位改為「第一次收錄時發下去的身分證號」：日期與標題照常更新，
    號碼不再跟著變。回傳沿用筆數供日誌顯示。
    """
    prev_id_by_url = {}
    for ev in previous_events:
        key = url_dedup_key(ev, src_urls)
        if key and ev.get("id"):
            prev_id_by_url.setdefault(key, ev["id"])

    live_ids = {ev.get("id") for ev in new_events if ev.get("id")}
    inherited = 0
    for ev in new_events:
        key = url_dedup_key(ev, src_urls)
        old_id = prev_id_by_url.get(key) if key else None
        if not old_id or old_id == ev.get("id"):
            continue
        if old_id in live_ids:
            # 撞上本批另一筆活動的 id。沿用會讓兩個不同活動合而為一，
            # 寧可讓這筆換號（漂移只是收藏失效，合併是資料錯誤）。
            continue
        live_ids.discard(ev["id"])
        ev["id"] = old_id
        live_ids.add(old_id)
        inherited += 1
    return inherited


def merge_events(new_events, previous_events):
    """
    新抽取的活動優先，其後補上既有未過期活動。
    去重鍵：id（第一次收錄時發下的號碼，見 inherit_ids）；輔助鍵：活動專屬詳情頁網址
    （同一活動即使兩次翻譯的標題略有差異，也能靠詳情頁網址擋掉重複）。
    """
    # ⚠️⚠️ **`FOLLOWED_URLS` 一定要併進來**（2026-09-04，兩段抓取上線時修的）。
    # `url_dedup_key` 的規則是「網址等於某個來源的列表頁 → 不可當去重鍵」，
    # 而**行事曆頁同樣是一頁多筆活動的列表頁**，只是它不在 `SOURCES` 裡。
    # 少了這一行，同一家店從同一份行事曆抽出的 5 筆活動會**共用同一個去重鍵，
    # 只留第一筆**——每家店 5 筆變 1 筆，而且沒有任何錯誤訊息。
    # 這是地雷 #8 換一個長相：那條講的是「移除來源會讓舊活動共用鍵」，這裡是
    # 「新增一個不在 SOURCES 裡的列表頁」。**日後再加任何兩段抓取都要記得這一步。**
    src_urls = {s["url"] for s in SOURCES} | FOLLOWED_URLS
    inherited = inherit_ids(new_events, previous_events, src_urls)
    if inherited:
        print(f"[db] {inherited} 筆活動沿用既有 id（標題或日期有變動，收藏不受影響）")
    merged, seen_ids, seen_urls = [], set(), set()
    dropped_area = 0
    for ev in list(new_events) + list(previous_events):
        d_end = valid_date(ev.get("date_end"))
        if d_end is None or d_end < TODAY:
            continue
        # 既有資料若地區已不在 AREAS（抓取範圍調整過）或場地在範圍外，一併剔除。
        # 少了這道，範圍外的舊活動會一路留到過期為止——曾有一筆撐到 11 個月後。
        if ev.get("area") not in AREAS or venue_out_of_scope(ev):
            dropped_area += 1
            continue
        ev_id = ev.get("id", "")
        url_key = url_dedup_key(ev, src_urls)
        if ev_id in seen_ids or (url_key and url_key in seen_urls):
            continue
        seen_ids.add(ev_id)
        if url_key:
            seen_urls.add(url_key)
        merged.append(ev)
    if dropped_area:
        print(f"[db] 剔除 {dropped_area} 筆地區已不在抓取範圍內的舊活動")
    merged.sort(key=lambda e: (e["date_start"], e["date_end"]))
    return merged


def stamp_first_seen(merged, previous):
    """
    首次收錄日（前端「新收錄」篩選的依據）。

    **與 id 同一條原則：發下去就不再重算。** 標題與日期每天都會被 LLM 重新解讀，
    若跟著重算，每天都會有一批舊活動假裝是新的——那正好是這個欄位要解決的問題的相反。
    id 已由 inherit_ids 穩定下來，所以這裡直接拿 id 對照即可。

    ⚠️ 既有活動缺這個欄位時**刻意留空，不是填今天**（回填之前產生的資料、
    或回填漏掉的）。填今天會讓一整批舊活動一次全部變成「新收錄」，
    前端那顆 chip 會從 27 筆暴增成整個網站。留空則被前端當成「不是新的」——
    失敗方向是安全的。
    """
    today = TODAY.isoformat()
    prev_seen = {
        ev["id"]: ev["first_seen"]
        for ev in previous if ev.get("id") and ev.get("first_seen")
    }
    prev_ids = {ev.get("id") for ev in previous if ev.get("id")}
    fresh = 0
    for ev in merged:
        seen = ev.get("first_seen") or prev_seen.get(ev.get("id"))
        if seen:
            ev["first_seen"] = seen
        elif ev.get("id") in prev_ids:
            ev["first_seen"] = ""
        else:
            ev["first_seen"] = today
            fresh += 1
    return fresh


