def is_dead_page(text):
    """**只檢查 Jina 的 `Title:` 那一行**，避免正文中出現這些字詞造成誤判

    ⚠️⚠️ **2026-09-04 由「前 600 字」收窄成「只看標題」，起因是一次真的誤殺。**
    寶可夢中心每家店的活動清單頁 `/shop/<店>/events/`，**第一行內容**就是
    `該当するイベント・キャンペーンが見つかりませんでした。`（＝「目前的篩選沒有符合的」，
    是**篩選結果訊息**不是「找不到這一頁」），而它落在前 600 字裡、
    「見つかりません」又正在 `SOFT_404_MARKS` 中 → **整頁被丟掉**。
    那一頁其實活著、底下真的列著活動，**而且它才是活動的正本**
    （店鋪首頁只有摘要，且首頁的活動區長期是空的）。
    **症狀是「寶可夢的活動一直很少」，沒有任何錯誤訊息。**

    **收窄是安全的，這是量出來的不是猜的**：把歷史上與 2026-09-04 實測到的
    **13 個** 404 頁標題全部拿來比對，**13 個全部只靠標題就抓得到**
    （群馬縣立近代美術館／日光旅ナビ／大阪觀光局／岐阜／三重／熊本／沖繩官方／
    和歌山／愛媛／岡山／長崎／寶可夢 shop 首頁／東北観光推進機構）。
    也就是說「正文比對」這一段**從來沒有獨力擋下過任何一頁**，只帶來誤殺風險。
    ⚠️ **沒有 `Title:` 行時退回舊的前 600 字窗口**，保住既有把關（失敗方向安全）。

    ⚠️ **日後想再放寬 `SOFT_404_MARKS` 之前先讀這一條**：清單愈長，
    「正文剛好出現這些字」的機率愈高，而**篩選結果訊息與 404 頁用的是同一批字**。

    ⚠️ **來源站回暫時性錯誤時，Jina 會把錯誤碼寫進它自己編的 Title，
    那個 Title 不是頁面內容，不可以拿來判死連結**（2026-08-20 實測踩到）。
    東京都現代美術館對 Jina 回 **403**，Jina 於是產出
    `Title: 404 Not Found` ＋ 下一行 `Warning: Target URL returned error 403`，
    而**內容照常抓到 9,675 字、第一段就是「開館時間 10:00-18:00」**。
    舊版在 `SOFT_404_MARKS` 命中那個假標題 → 整頁丟掉。

    這正好架空了地雷 #6d：「429／403／5xx 只是暫時被擋，Jina 往往仍拿得到內容」
    那條規則寫在 `fetch_page_text()` 裡，而本函式**擋在它前面**，
    所以只要 Jina 污染了 Title，那條保護就永遠走不到。

    故：**已經讀到一個「非死連結」的錯誤碼時，跳過軟性 404 的字串比對。**
    其餘情況一律不變——沒有錯誤標記的頁面照常比對（那是 64 個來源的常態，
    也是地雷 #6b 那五個「壞很久沒被發現」的來源唯一擋得住的方式），
    真正的 404／410 仍由上面那條直接擋掉。

    **刻意不放寬 404**：日光東照宮的 `/pages/25/` 是「來源站回 404 但內容正確」
    （該站伺服器設定的問題），放寬會讓「死連結偽裝成正常內容」重新出現，
    那個坑的代價遠大於偶爾漏掉一頁。
    """
    code = source_http_error(text)
    if code in DEAD_HTTP_CODES:
        return True
    if code:
        # 403／429／5xx：Title 由 Jina 編造，不能當證據。內容長度由呼叫端把關。
        return False
    title = jina_title(text)
    # 沒有 Title 行時退回舊的「前 600 字」窗口，保住既有的把關（失敗方向安全）
    zone = title.lower() if title is not None else text[:600].lower()
    return any(m in zone for m in SOFT_404_MARKS)


def fetch_page_text(url, locale=None, nocache=False):
    """Jina Reader 抓來源頁純文字。`locale` 與 `nocache` 只有需要的來源才傳（見下）。

    ⚠️ **`x-locale` 刻意做成逐來源開關，不是全域套用**（2026-08-28）。
    它是 Jina 自己的參數，用來設定它那台無頭瀏覽器的語系；不送的話它看起來就是個
    美國來的訪客，**多語系網站會回英文版**——實測大阪觀光局 `osaka-info.jp/event/`
    回 9,382 字而**日文字元 0 個**，標題是「30 results found...」。
    那會讓 LLM 把英文照抄進 `title_ja`／`venue_ja`，而 `venue_ja` 正是查座標的依據
    → 座標查不到、日文模式顯示英文，**而來源正常、活動照抽、統計照印，完全看不出來**。
    （`build_places.py` 的 `fetch_page()` 2026-08-20 就在送這個 header 了，只有這支沒有。）

    **為什麼不全域套用**：拿正式清單的 64 個來源做過 A/B（同網址連續抓兩次），
    60 個沒有實質差異、2 個明顯變好，**但「藤澤觀光官方」會變差**——
    16,905 字／48 個日期 → 10,996 字／39 個日期，**各抓兩次都穩定重現**。
    無條件送出去等於拿一個既有來源的 9 個日期去換，而那是靜默的。
    故預設維持原行為（既有 64 個來源逐位元組不變），**只有實測確認需要的來源才在
    `SOURCES` 裡標 `"locale": "ja-JP"`**。

    ⚠️⚠️ **量這件事一定要有 A/A 對照。** 第一輪單次 A/B 曾得出「x-locale 修好了鐵道博物館
    （日期 0 → 10）」與「前橋觀光變差了」兩個結論，**兩個都是錯的**：同一個網址不帶 header
    連抓兩次，鐵道博物館是 0 → 10 個日期、前橋是 17,363 → 5,173 字。
    **Jina 的單次抓取波動比這個 header 的影響還大**，一次取樣證明不了任何事。

    ⚠️ **`Accept-Language: ja` 沒有用**（那是給來源站看的，Jina 不轉送），別再試那條。

    ⚠️⚠️ **`nocache` 是第二個逐來源開關（2026-09-04），起因是一種新的壞法：
    Jina 的快取裡可能存著一份「渲染不完整」的舊版本，而它看起來完全正常。**
    `Walker+ 北海道祭典` 實測 `[page] 8557 字 → [ok] 抽取 0 筆`，
    但那一頁直接 `curl` 是 135KB、明寫「全21件」、第一頁 10 筆全在辦：
    **Jina 回的那份 HTTP 200、內容通順、沒有任何錯誤標記，只是整個活動列表不在裡面**
    （`Published Time` 停在 2025-05-08）。加上這個 header 立刻變成 29,920 位元組、列表全回來。

    **這是「素材根本沒被餵進去」那一族的第二個實例**（第一個是 2026-08-21 都廳展望室
    的 `HOURS_KEY_RE` 漏詞）。共同點是**抓取成功、字數合理、模型也很認真，
    但要抽的東西從來沒進到 prompt 裡**，於是失敗長得像「這一頁沒有活動」。
    ⚠️ **字數擋不住它**：8,557 字不算異常小（既有來源有更短的照樣抽得到），
    **唯一分得出來的是「同類頁面之間的落差」**——五個縣的祭典頁另外四個是 26,671～38,499 字。

    ⚠️⚠️ **為什麼不全域套用**（同 `x-locale` 那條的理由，但代價不同）：
    無條件送出去等於**要求 Jina 對 100 個來源每天各重新渲染一次**，既拖慢整輪
    （現況 59 分），也加重我們在免費額度上的負擔，而**受害的來源只有這一個**。
    故預設維持原行為，**只有實測確認被快取住的來源才在 `SOURCES` 裡標 `"nocache": True`**。

    ⚠️ **它治不了根**：快取是 Jina 那邊的狀態，哪天它自己過期了這個旗標就只是白花時間
    （無害）。反過來，**日後若有別的來源突然「字數掉一截又抽 0 筆」，先來試這個旗標，
    不要急著改 prompt 或換網址。**

    ⚠️⚠️ **這個旗標上線當下是「驗不出差別」的，而原因本身值得記：診斷動作把被診斷的
    對象改掉了。** 查根因時那一發 `x-no-cache` **寫穿了 Jina 的共用快取**——
    事後不帶旗標連抓三次全部是 24,335～24,384 字／11 個日期／四個祭典名稱都在，
    **與帶旗標的 24,288 字沒有實質差別**。也就是說**這一頁在改動落地之前就已經自己好了**，
    旗標現在的角色是保險不是修復。
    ⚠️ **所以不要拿「A/B 沒差別」當成它沒作用的證據**——那個 8,557 字的舊 render
    從 2025-05-08 一路活到 2026-09-04（**橫跨十六個月、連抓兩次逐字元相同**），
    黏性極高，只是剛好被我們自己戳掉了。
    📌 **通則：這是「唯讀的診斷其實會留下副作用」的第二個實例**（第一個是 2026-09-02
    實打 Klook 聯盟端點，在使用者後台留下一個刪不掉的 ADID）。**排查前先想一下
    這一發會不會改變現場**，否則就會像這次一樣——**問題修好了，卻再也證明不了它壞過。**
    """
    jina_url = "https://r.jina.ai/" + url
    headers = {"User-Agent": "Mozilla/5.0"}
    if locale:
        headers["x-locale"] = locale
    if nocache:
        headers["x-no-cache"] = "true"
    if JINA_API_KEY:
        headers["Authorization"] = "Bearer " + JINA_API_KEY
    for attempt in range(RETRY):
        try:
            text = http_get(jina_url, headers=headers)
            # 死連結偵測。長度檢查完全擋不住這兩種情況，會把「找不到頁面」當成正常
            # 內容送進 LLM 白花一次呼叫，而且從紀錄上看起來一切正常——Walker+ 的兩個
            # 祭典來源就這樣壞了很久沒被發現。重試沒有意義，直接放棄。
            if is_dead_page(text):
                print(f"  [fail] 來源頁是死連結或錯誤頁，網址可能已失效：{url}")
                return None
            if len(text.strip()) > 200:
                # 來源站回了錯誤碼但 Jina 仍取得內容（多半是 429 限速）。內容可用就照常使用，
                # 只是把狀況記在日誌上——這行若天天出現，代表該站開始擋我們了。
                code = source_http_error(text)
                if code:
                    print(f"  [warn] 來源站回 HTTP {code}（限速或暫時故障），"
                          f"但 Jina 已取得 {len(text)} 字內容，照常使用")
                return text[:MAX_PAGE_CHARS]
            print(f"  [warn] 內容過短（{len(text)} 字），重試")
        except (urllib.error.URLError, urllib.error.HTTPError, OSError) as e:
            print(f"  [warn] Jina 抓取失敗（{attempt + 1}/{RETRY}）：{e}")
        if attempt < RETRY - 1:
            time.sleep(RETRY_WAIT)
    return None


