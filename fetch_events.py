def future_date_count(text, today=None):
    """這一頁上有幾個「還沒過完」的日期。**只用來判斷值不值得警告，不作他用。**

    ⚠️ **沒有年份的日期一律映射到「今年」，絕對不要退到明年。**
    花火頁在九月列的全是 7、8 月的舊活動，映射到明年就會變成一整頁的「未來日期」
    ——那會讓這個警告**每一輪都對同一批來源響**，而永遠在響的警報等於沒有警報
    （同 `no_hours` 那條）。映射到今年，它們自然變成過去式而被排除。
    """
    today = today or TODAY
    body = _URL_RE.sub(" ", text)
    found = set()
    for rx in _DATE_Y_RES:
        for y, m, d in rx.findall(body):
            try:
                found.add(date(int(y), int(m), int(d)))
            except ValueError:
                pass          # 2026.13.45 那種假命中，丟掉
    for m, d in _DATE_MD_RE.findall(body):
        try:
            found.add(date(today.year, int(m), int(d)))
        except ValueError:
            pass
    return sum(1 for x in found if x >= today)


