def _segments(s):
    """把並列的多個地點拆開，回傳長度 ≥2 的片段（保留順序）"""
    return [p.strip(" 　・") for p in _SPLIT_MULTI.split(s) if len(p.strip(" 　・")) >= 2]


# 尾部的附屬設施詞。**Photon 是整串比對，尾部多一個詞就整個落空**：實測
# 「渋谷ヒカリエホール」查無、「渋谷ヒカリエ」命中（35.6592,139.7037，正確）。
# simplify_venue 的 VENUE_TRIM 只在這些詞前面**有空白**時才剝（那是為了避免砍掉
# 「さくら広場」這種名稱本體），於是黏在一起寫的全部漏掉。
#
# 剝完長度須 ≥ MIN_QUERY_LEN，所以「東京ドーム」不會被剝成「東京」。
# **刻意不含「河畔／河川敷／橋」**——「利根川河畔」剝成「利根川」會查到一條 200km 長的
# 河，落點可能差數十公里，那是地雷 #3 說的「錯座標比查不到更糟」。
TAIL_FACILITY = (
    "ホール", "アリーナ", "ギャラリー", "スタジオ", "シアター", "劇場",
    "展示場", "展示室", "体育館", "会館", "広場", "駐車場",
    "御本社", "本殿", "参道", "境内", "敷地内", "周回コース", "前広場",
    "入口", "正面", "特設会場", "メイン会場", "会場",
)
MIN_QUERY_LEN = 4          # 切分／剝除後的查詢字串下限，短於此一律不查
_KANJI_RE = re.compile(r"[一-鿿]")
_SPACE_RE = re.compile(r"[\s　]+")
# 泛用區域說法：出現在切分／剝尾後的候選裡，代表這串不是一個具體地點。
# 與 VAGUE_SEGMENTS（完全比對）互補——那份清單擋的是「整串就是泛用詞」，
# 這條擋的是「剝完之後半截仍是泛用詞」，例如「横浜市内の会場」→「横浜市内の」。
_VAGUE_PART_RE = re.compile(r"市内|町内|村内|区内|都内|県内|各所|各地|周辺|一帯|エリア|沿線|近郊")


def strip_tail_facility(s, times=2):
    """
    反覆剝掉尾部的附屬設施詞，每剝一次產生一個候選（由長到短，先試長的）。
      「日光二荒山神社御本社境内」→「日光二荒山神社御本社」→「日光二荒山神社」
      「館林市役所敷地内」        →「館林市役所」
    剝兩次就停：再往下多半已經不是場地名了。
    """
    outs, cur = [], s.strip()
    for _ in range(times):
        for t in TAIL_FACILITY:
            if cur.endswith(t) and len(cur) - len(t) >= MIN_QUERY_LEN:
                cur = cur[: -len(t)].strip(" 　・、,")
                outs.append(cur)
                break
        else:
            break
    return outs


def venue_variants(name):
    """
    產生額外的查詢寫法，回傳順序即嘗試順序。**只切字串，不做任何對錯判斷**——
    切完的每一段仍要走 geocode_osm 的 name_confidence 把關，與整串查詢一視同仁。

    要處理的三種寫法（全部來自實際資料）：
      「小山市/観晃橋下流 思川河畔」→ 斜線前是市名，後面才是場地（Walker+ 花火頁的慣例）
      「鬼怒川河畔、橋本運動公園」  → 兩個地點並列，實測第二個才查得到，故每段都試
      「唐澤山神社 参道（栃木県…）」→ 剝掉括號後重切一次

    括號裡的地址**刻意不整串拿去查**：實測「栃木県日光市山内2307」會回「栃木県農業試験場」
    （差 20km），地址查詢在 Nominatim 上不可靠。括號只用來挖市町村名，交給 city_name_of()。
    """
    out = []

    def add(s):
        # 一律剝掉括號再當查詢用。括號裡多半是地址或註記，而**地址查詢在 Nominatim 上
        # 不可靠**——實測「栃木県日光市山内2307」回「栃木県農業試験場」，差 20km。
        # 括號裡的地址改由 city_name_of() 挖市町村名，那條路才安全。
        s = _PAREN_RE.sub("", s)
        s = re.sub(r"[\s　]+", " ", s).strip(" 　・、,／/～~")
        if len(s) >= 2 and s != name and s not in out and s not in VAGUE_SEGMENTS:
            out.append(s)

    # ① 斜線切分：**只在斜線前面真的是市町村名時才做**。這條規則是為了 Walker+ 花火頁的
    #    「日光市/日光だいや川公園」慣例而存在；若無條件套用，「洒落CAFE 東京/大阪/福岡」
    #    這種多城市列舉會被切成「大阪/福岡」之類的垃圾查詢。
    slash = [p for p in re.split(r"[/／]", name) if p.strip()]
    if len(slash) >= 2 and city_name_of(slash[0]):
        head = slash[0].strip()
        for seg in _segments("/".join(slash[1:]))[:2]:
            add(head + " " + seg)   # 帶市名的先試：同名場地在別縣時，市名是唯一的區分依據
            add(seg)

    # ② 並列地點：每一段都是候選（不能只取第一個，實測第一個常查不到）
    for seg in _segments(name)[:3]:
        add(seg)

    # ③ 剝掉括號後再切一次
    bare = _PAREN_RE.sub("", name)
    if bare != name:
        for seg in _segments(bare)[:2]:
            add(seg)

    core = bare.strip()

    def add_long(s):
        """
        ④以下的候選一律要求長度 ≥ MIN_QUERY_LEN，且不得含泛用區域說法。

        `VAGUE_SEGMENTS` 是**完全比對**，擋不住剝尾剝出來的半截詞：實測
        「横浜市内の会場」剝掉尾部的「会場」後變成「横浜市内の」，查到橫濱北部，
        離原本的 AI 座標 15.4km。**剝尾會製造出原本不存在的字串**，所以這裡要用
        模式比對再擋一次。只作用在④～⑦這些新切法上，①～③維持原行為。
        """
        if len(s) >= MIN_QUERY_LEN and not _VAGUE_PART_RE.search(s):
            add(s)

    # ④ 中黑點切分：後段多半是館內的附屬設施（「…交流センター・流水プール」
    #    「…大学美術館・陳列館」）。**只取第一段**，並同時給一個去空白版本——
    #    Photon 對空白敏感，實測「東京藝術大学 大学美術館」要寫成
    #    「東京藝術大学大学美術館」才查得到上野校區（差 0.25km）。
    #    這個順序很重要：**去空白版必須排在⑥的「東京藝術大学」之前**，
    #    否則會查到足立區的千住校區，差 8km 而且兩道守門都擋不住（名稱相符、同縣）。
    #    第一段**同樣要求含漢字**，理由與⑥相同：「ツタンカーメン・ミュージアム」的
    #    中黑點是名稱本體的一部分，切出「ツタンカーメン」只會查到不相干的地方。
    if "・" in core:
        head = core.split("・")[0].strip()
        if _KANJI_RE.search(head):
            add_long(head)
            add_long(_SPACE_RE.sub("", head))

    # ⑤ 整串去空白
    add_long(_SPACE_RE.sub("", core))

    # ⑥ 空白切分取主體。**片段必須含漢字**——空白是英文的正常分詞符號，少了這道限制
    #    會切出「GINZA」「THE」「MUJI」這種片段，而查「GINZA」回銀座在 name_confidence
    #    眼中是 weak、Nominatim 照樣採用，直接就是錯座標（實測 9 筆純英文／片假名
    #    場地名全靠這條擋掉）。取「第一個夠長且含漢字」的段，故「旧 みどり市立神梅小学校」
    #    會跳過開頭的「旧」，「AQURAHOME 宇都宮西展示場」會跳過無漢字的品牌名。
    segs = [p.strip() for p in _SPACE_RE.split(core) if p.strip()]
    main = next((s for s in segs if len(s) >= MIN_QUERY_LEN and _KANJI_RE.search(s)), None)
    if main and main != core:
        add_long(main)

    # ⑦ 尾部設施詞剝除（「館林市役所敷地内」→「館林市役所」）。
    #    **對①～③切出的片段也要套**——「日光二荒山神社御本社境内及び世界遺産…」
    #    是先由②的「及び」切出「日光二荒山神社御本社境内」，再剝兩次尾部才會得到
    #    「日光二荒山神社」。只對原名剝的話這一筆救不到。
    #    list(out) 是迭代前的快照，迴圈內 add_long 追加的候選不會再被掃一次。
    for base in ([core] + ([main] if main else []) + list(out)):
        for s in strip_tail_facility(base):
            add_long(s)

    return out[:MAX_VARIANTS]


# 分店後綴：「東武百貨店 池袋店」的「池袋店」。**長度設上限**是為了不讓
# 「…ミュージアム店」這種很長的一整段被當成後綴。
_BRANCH_SUFFIX_RE = re.compile(r"^[^\s　]{1,8}店$")


def branch_trimmed(name, variant):
    """
    `variant` 是不是 `name` 剝掉尾端「〜店」分店後綴的結果。

    ⚠️ **這個判準的用途是「限制作用範圍」，不是切字串**——它只服務 geocode 最後那一段
    「切分變體 ＋ 行政區」。無條件把所有變體都配上行政區會組出
    「5F 武蔵野 埼玉県」「本館2Ｆ 埼玉県」「1F グランド 埼玉県」這種垃圾查詢，
    而它們**查得到東西、查到的是別的地方**，正是地雷 #3 說的「錯座標比查不到更糟」。
    要求掉的那一截**整個**是「〜店」，上面那三種就都不會通過（實測全站只有 3 筆通過，
    其中 2 筆不受影響、1 筆被修好）。
    """
    base = _SPACE_RE.sub("", name)
    v = _SPACE_RE.sub("", variant)
    if v == base or not base.startswith(v):
        return False
    return bool(_BRANCH_SUFFIX_RE.match(base[len(v):]))


# 並列分隔符。用在 branch_only：掉的那一截若以它們開頭，那是「另一個地點」而不是分店後綴。
_JOIN_HEAD_RE = re.compile(r"^[/／、，,・･&＆]")


def branch_only(name, variant):
    """
    `variant` 是不是 `name` **純粹**剝掉尾端分店後綴的結果（＝一個光禿禿的品牌名）。

    這種字串**不可以單獨拿去查**：查到的必然是同品牌的另一家分店，而且
    「品牌名 ⊂ 品牌名＋分店名」讓 `name_confidence` 一定判 strong、兩家又同縣，
    於是 `pref_gate` 也擋不住。實測 `ねんりん家 大丸東京店` 切出 `ねんりん家`，
    Photon 回 `ねんりん家 銀座本店`——**自信地釘在 1.2km 外**。
    ⚠️ **與第一百四十五筆餐廳端 `osm_query_key` 修過的「關鍵字取到分店名」是同一族**，
    只是活動這支當時沒跟著修。

    ⚠️ **並列寫法不算分店，這是它與 `branch_trimmed` 唯一的差別。**
    `横浜ワールドポーターズ / 西武渋谷店` 掉的那截是 `/西武渋谷店`，`branch_trimmed`
    會判 True（`/` 也是非空白字元），但前面那個是**另一個完整的場地名**、而且
    現在查得到、座標正確——把它擋掉等於把一筆對的變成退回地區中心。
    判準就是「掉的那一截**不以並列分隔符開頭**」。

    ⚠️ **只擋「單獨查」，不擋「品牌名＋行政區」那個段位**（第一百四十四筆靠它把
    `東武百貨店 池袋店` 從駿河灣海上救回池袋）。那一段仍然走 `branch_trimmed`。
    """
    if not branch_trimmed(name, variant):
        return False
    tail = _SPACE_RE.sub("", name)[len(_SPACE_RE.sub("", variant)):]
    return not _JOIN_HEAD_RE.match(tail)


# 「這個活動不在單一地點」的寫法。查了必然得到其中一家分店，或碰巧字面相似的某處。
MULTI_SITE_RE = re.compile(
    r"全国|全國|全店|各店|各館|各所|各会場|\d+\s*店舗|店舗$|"
    r"(?:東京|大阪|名古屋|福岡|札幌|仙台|横浜|京都|神戸)会場$"
)


def is_multi_site(name):
    """
    場地名代表「多個地點」或只是泛用說法時回 True——**這種活動不該去查座標**。

    起因是 Photon 的實測結果：它把「SUBWAY (サブウェイ) 全國」配到表參道某家分店、
    「スイーツパラダイス店舗」配到另一家分店、「and GALLERY4店舗」配到四家中的一家。
    座標本身「存在」，但拿它代表一個全國同步的活動是誤導——使用者照著圖釘走過去，
    看到的是一家沒有在辦活動的分店。

    Nominatim 沒暴露這個問題純粹因為它保守（地址解析器查不到就回空）。
    既然換了更會找的搜尋引擎，就得自己補上這道判斷。
    退回地區中心並標成「概略位置」，才是對這類活動誠實的表示法。
    """
    s = (name or "").strip()
    return s in VAGUE_SEGMENTS or bool(MULTI_SITE_RE.search(s))


def city_name_of(text):
    """
    從場地名或地址中認出市町村名，回傳名稱字串，認不出回 ""。**不管它在哪一縣。**

    取**最長匹配**，否則「那須塩原市」會被較短的市名搶先（清單裡沒有子字串關係時無妨，
    但「大田原市」與「大田区」這類字面重疊的情況必須讓長的贏）。

    ⚠️ **與 `city_of` 分成兩支是刻意的**（2026-09-04）：只要「名字」的呼叫端
    （`venue_variants` 判斷斜線前面是不是市町村、`geocode` 組「場地名＋市町村」查詢字串）
    **不該因為那個名字剛好全國有兩個而失效**——府中市在東京與廣島都有，但兩邊
    寫進查詢字串的都是「府中市」三個字，一模一樣。合成一支的話，撞名的市町村
    會讓那兩處靜默少掉一個查詢段位，**而那只會表現成「這個場地查不到座標」**。

    ⚠️⚠️ **一樣長的時候「区」要輸給市町村**（2026-09-04 修）。政令指定都市的區名與
    東京 23 區同名的有一堆（中央区・北区・港区・西区…），而它們都是三個字、
    跟「札幌市」「大阪市」一樣長——舊版的 `len(city) > len(best)` 在一樣長時
    **保留先遍歷到的那個**，而東京都的區塊排在前面，於是
    `札幌市中央区北1条` 認出的是**東京都中央区**。
    後果被 `fallback_center` 那道縣別守門接住了（退回縣級），所以看起來只是
    「這個活動的位置不太準」，**但 PREF_CITIES 那句「場地名寫『大阪市北区中之島』時
    city_of 仍會命中『大阪市』」在改這條之前其實是錯的**。
    """
    best, best_key = "", (0, 0)
    for city in CITY_PREF:
        if city in text:
            key = (len(city), 0 if city.endswith("区") else 1)
            if key > best_key:
                best, best_key = city, key
    return best


def city_of(text, allowed=None):
    """
    從場地名或地址中認出市町村，回傳 (市町村名, 縣名)，認不出回 None。

    ⚠️ **撞名時靠 `allowed`（這個地區桶接受哪些縣，見 AREA_PREF_OK）消歧義。**
    全國同名的市町村有 25 組：廣島的「府中市」與東京的「府中市」名字一樣，
    但**桶不一樣**，所以「廣島」桶問到府中市時答案唯一。
    ⚠️ **仍然不唯一就回 None**（例如「金山町」在山形與福島，而兩者同屬「東北」桶）：
    退回縣中心是 30km 級的誤差，指到另一座城市卻可能是好幾百公里，
    **失敗方向必須偏向前者**（同 fallback_center 的既有守門）。

    ⚠️ **單一候選時不看 `allowed`，照原樣回傳**——「這個縣合不合這個桶」是呼叫端
    既有那道守門的責任（它會 bump `fallback_city_rejected`），這裡不重複做，
    否則那個計數器會靜默歸零，而它正是「撞到同名地名」的唯一觀測點。
    """
    best = city_name_of(text)
    if not best:
        return None
    prefs = CITY_PREF[best]
    if len(prefs) == 1:
        return (best, prefs[0])
    if allowed:
        cand = [p for p in prefs if p in allowed]
        if len(cand) == 1:
            return (best, cand[0])
    bump("city_ambiguous")
    return None


def pref_of(text):
    """場地名直接寫了縣名時取出（「栃木県日光市山内2307」→「栃木県」）"""
    for pref in PREF_CENTER:
        if pref in text:
            return pref
    return None


def haversine_km(a, b):
    """兩座標間距離（公里）"""
    from math import radians, sin, cos, asin, sqrt
    lat1, lng1, lat2, lng2 = map(radians, (a[0], a[1], b[0], b[1]))
    dlat, dlng = lat2 - lat1, lng2 - lng1
    h = sin(dlat / 2) ** 2 + cos(lat1) * cos(lat2) * sin(dlng / 2) ** 2
    return 2 * 6371 * asin(sqrt(h))


def in_bbox(lat, lng):
    lat_min, lng_min, lat_max, lng_max = GEO_BBOX
    return lat_min <= lat <= lat_max and lng_min <= lng <= lng_max


def _strip_generic(s):
    s = _PUNCT_RE.sub("", s)
    for w in GENERIC_WORDS:
        s = s.replace(w, "")
    return s


_JA_RE = re.compile(r"[぀-ヿ一-鿿]")
_LATIN_RE = re.compile(r"[A-Za-z]")


def _script(s):
    """判斷字串的文字系統，用來決定字元比對有沒有意義"""
    ja, la = len(_JA_RE.findall(s)), len(_LATIN_RE.findall(s))
    if ja and not la:
        return "ja"
    if la and not ja:
        return "latin"
    return "mixed"


def _en_keywords(s):
    """英文名稱切成「有識別力的單字」集合。回傳 (特徵字, 弱字)。"""
    words = _EN_WORD_RE.findall(s.lower())
    keep = [w for w in words if w not in EN_GENERIC_WORDS]
    return {w for w in keep if w not in EN_WEAK_WORDS}, {w for w in keep if w in EN_WEAK_WORDS}


def _latin_confidence(q, f):
    """
    純英文對純英文的比對：**比單字，不比字母**。

    根因是**英文只有 26 個字母**，字元重疊率在這裡幾乎沒有鑑別力——
    實測「TOKYO NODE GALLERY A/B/C」對上毫不相干的「RED AND BLUE GALLERY」
    重疊率高達 0.69，超過 NAME_MATCH_MIN 而被判 strong，於是活動被自信地
    釘在 2.4km 外的中央区（真正的 TOKYO NODE 在港区虎ノ門）。
    日文漢字上千個，同樣的門檻在那邊是有意義的，所以只換掉英文這條路。
    """
    kq, wq = _en_keywords(q)
    kf, wf = _en_keywords(f)
    if kq & kf:
        return "strong"            # 至少一個特徵字對得上
    if kq or kf:
        return ""                  # 兩邊都有特徵字卻毫無交集 → 是別家
    # 剝到只剩泛用詞與弱詞（「Tokyo Art Center」vs「Tokyo Gallery」）。
    # 這種沒有識別力，不能當作證據，但也不宜斷言是別家 → 交給不確定標記。
    return "weak" if wq & wf else ""


# 片假名（全形 ゠-ヿ 與半形 ｦ-ﾟ）。長音符 ー 與中黑 ・ 都落在這個區段內。
_KANA_ONLY_RE = re.compile(r"^[゠-ヿｦ-ﾟ]+$")
# 片假名比對的門檻：**最長公共子串**佔較短那一方的比例。
# ⚠️ **量出來的，不是挑的**：全站 44 個純片假名查詢字串兩兩配對，現行的字元重疊率
# 會判 strong 的非包含配對有 19 組、**全部是毫不相干的地方**，而那 19 組的
# 最長公共子串比例**最高只有 0.50**；要擋的 `ヴェールカフェ`×`ヴェールフェリーチェ`
# 是 0.57。0.6 落在兩者之間，且與 NAME_MATCH_MIN 同值。
KANA_MATCH_MIN = 0.6


def _kana_only(s):
    return bool(_KANA_ONLY_RE.match(s))


def _lcs_len(a, b):
    """最長**連續**公共子串的長度（不是最長公共子序列——後者會把散落的音符也算進去）。"""
    prev = [0] * (len(b) + 1)
    best = 0
    for ca in a:
        cur = [0] * (len(b) + 1)
        for j, cb in enumerate(b, 1):
            if ca == cb:
                cur[j] = prev[j - 1] + 1
                if cur[j] > best:
                    best = cur[j]
        prev = cur
    return best


def _kana_confidence(q, f):
    """
    純片假名對純片假名的比對：**比最長連續子串，不比字元集合**。

    根因與 `_latin_confidence` 完全相同，只是換一種文字：**片假名的字元集小**，
    而且 ー ェ ッ ン 這類音符在每個名字裡都出現，字元集合比對因此幾乎沒有鑑別力。
    實測 `スパ` 對上 `ユニバーサルスタジオジャパン` 重疊率是 **1.00**、
    `サントリー` 對上 `シェラトングランデトーキョーベイホテル` 是 0.60——全部判 strong。

    真正把這件事變成錯座標的是 `ヴェールカフェ（行田市水城公園）`：Photon 配到
    和光市一個叫 `ヴェールフェリーチェ` 的**自行車租借站**（重疊率 0.83），
    縣別相同所以 `pref_gate` 也擋不住，於是**錯 41km 而標成 precise（實心圖釘）**。

    ⚠️ 「互為子字串」那條在呼叫端已經先判過了（`大丸` vs `大丸東京店`），
    所以走到這裡的必然是「誰也不包含誰」，這時共用的開頭有多長才是證據。
    """
    return "strong" if _lcs_len(q, f) / min(len(q), len(f)) >= KANA_MATCH_MIN else ""


def name_confidence(query, found):
    """
    比對查詢名與回傳地點名，回傳 'strong' / 'weak' / ''（不吻合）。

    要擋的是這種：查「目黒区美術館」回「東京都写真美術館」——同語言但根本是別家，
    採信會得到自信的錯座標，比查不到更糟。

    但**不能**用同一把尺去擋文字系統不同的情況。地圖資料庫常以另一種文字收錄同一個
    地點（查「横浜ワールドポーターズ」回「Yokohama World Porters」、查「EKIMISE」回
    「浅草エキミセ」），字元重疊率必然是 0，卻都是正確結果。這類判為 'weak'：
    採用座標，但標記為不確定，讓前端顯示成概略位置而非精確位置。

    **兩邊都是純英文時走 `_latin_confidence`（比單字）、兩邊都是純片假名時走
    `_kana_confidence`（比最長連續子串）**，其餘一律維持字元比對——
    含漢字的名字那條路一個字都沒動（漢字上千個，同一個門檻在那邊是有意義的）。
    """
    q, f = _strip_generic(query).lower(), _strip_generic(found).lower()
    if not q or not f:
        return ""          # 剝完沒東西可比，無從判斷
    if len(q) >= 2 and (q in f or f in q):
        return "strong"    # 一方是另一方的簡稱，例如「大丸」vs「大丸東京店」
    sq, sf = _script(q), _script(f)
    if sq != "mixed" and sf != "mixed" and sq != sf:
        return "weak"      # 文字系統不同，字元比對無意義，交給不確定標記處理
    if sq == "latin" and sf == "latin":
        return _latin_confidence(query, found)   # 用原字串，標點是切單字的依據
    if _kana_only(q) and _kana_only(f):
        return _kana_confidence(q, f)            # 片假名字元集小，字元比對沒有鑑別力
    chars = set(q)
    if sum(1 for ch in chars if ch in f) / len(chars) >= NAME_MATCH_MIN:
        return "strong"
    return ""


def geocode_google(query, allowed_prefs=None):
    """Google 查座標。回傳 (lat, lng) 或 None。額度用盡／金鑰無效時停用 Google 而非中斷流程。"""
    global GOOGLE_ENABLED
    lat_min, lng_min, lat_max, lng_max = GEO_BBOX
    url = "https://maps.googleapis.com/maps/api/geocode/json?" + urllib.parse.urlencode({
        "address": query,
        "key": GOOGLE_GEOCODING_KEY,
        "language": "ja",
        "region": "jp",
        "bounds": f"{lat_min},{lng_min}|{lat_max},{lng_max}",
    })
    try:
        data = json.loads(http_get(url, headers={"User-Agent": "jp-events/2.0"}, timeout=30))
    except (urllib.error.URLError, urllib.error.HTTPError, OSError, json.JSONDecodeError) as e:
        print(f"    [geo] Google 連線失敗（{query}）：{e}")
        bump("google_error")
        return None

    status = data.get("status", "")
    if status in ("OVER_QUERY_LIMIT", "REQUEST_DENIED"):
        print(f"    [geo] Google 回報 {status}：{data.get('error_message', '')}")
        print("    [geo] 停用 Google，本次執行改用 OpenStreetMap")
        GOOGLE_ENABLED = False
        bump("google_error")
        return None
    if status != "OK" or not data.get("results"):
        bump("google_miss")
        return None

    r = data["results"][0]
    try:
        loc = r["geometry"]["location"]
        lat, lng = round(float(loc["lat"]), 6), round(float(loc["lng"]), 6)
    except (KeyError, TypeError, ValueError):
        bump("google_error")
        return None
    if not in_bbox(lat, lng):
        bump("google_out_of_range")
        return None
    # Google 自己就會標示信心度：partial_match 代表只是勉強配對，
    # APPROXIMATE 代表僅定位到城市層級——兩者都不足以當作精確的場地座標。
    if r.get("partial_match") or r["geometry"].get("location_type") == "APPROXIMATE":
        bump("google_low_confidence")
        return None
    # 與 OSM 同一道縣別守門。Google 目前停用（GOOGLE_ENABLED 為 False），但漏洞不該留著
    # 等日後啟用時重現——formatted_address 在 language=ja 下同樣帶縣名。
    if not pref_gate(r.get("formatted_address", ""), allowed_prefs):
        bump("google_pref_rejected")
        return None
    bump("google_hit")
    return (lat, lng, "strong")


def pref_gate(display_name, allowed):
    """
    回傳 True 代表這個查詢結果的所在縣與活動的地區桶相容。

    **這是切分查詢的安全網，缺了它就會出現自信的錯座標。** 實測：栃木大田原市的煙火，
    場地「大田原市/箒川岩井橋付近、佐久山運動公園」切出「佐久山運動公園」，Nominatim
    回長野縣的「大深山運動公園」——字元重疊率剛好 0.6 踩在 NAME_MATCH_MIN 上被判 strong，
    於是活動被精準地釘到 135km 外的長野縣。名稱比對這條路擋不住它，只有縣別能。

    display_name 認不出任何縣名時**放行**（Nominatim 偶爾回英文），
    寧可漏擋也不誤殺——誤殺會讓原本正確的結果退回概略位置。
    """
    if not allowed:
        return True
    found = [p for p in PREF_ALL if p in display_name]
    return not found or any(p in allowed for p in found)


def geocode_osm(query, allowed_prefs=None):
    """OpenStreetMap 查座標，限關東範圍，須通過名稱比對與縣別守門。限速 1 req/s。"""
    lat_min, lng_min, lat_max, lng_max = GEO_BBOX
    # ⚠️ **`countrycodes=jp` 不是保險，是必要的**（2026-08-29 加）。
    # `GEO_BBOX` 自 2026-08-28 放大成整個日本之後，那個矩形**必然含到鄰國**
    # （首爾、海參崴、中國東北都在框內），而**兩道守門一道都攔不住國外的結果**：
    # `pref_gate` 認不出日本縣名時是**放行**的（刻意的，見該函式），而國外的
    # `display_name` 永遠認不出；`name_confidence` 的字元比對又把簡體中文
    # 當成日文——實測 `中心市街地` 回**中國黑龍江省密山市**的「中心街道」，
    # 五個字全部重疊判 strong，於是一筆宇都宮的爵士祭被釘到 **1203km** 外，
    # 而 `geo` 是 `precise`＝實心圖釘。
    # ⚠️ 這是伺服器端的國別過濾，**日本境內的結果依定義完全不受影響**。
    url = (
        "https://nominatim.openstreetmap.org/search?format=json&limit=1"
        "&countrycodes=jp"
        f"&viewbox={lng_min},{lat_max},{lng_max},{lat_min}&bounded=1"
        "&q=" + urllib.parse.quote(query)
    )
    arr = None
    try:
        arr = json.loads(http_get(url, headers={"User-Agent": "jp-events/2.0 (github actions)"}))
    except (urllib.error.URLError, urllib.error.HTTPError, OSError, json.JSONDecodeError) as e:
        print(f"    [geo] OpenStreetMap 查詢失敗（{query}）：{e}")
        bump("osm_error")
    finally:
        time.sleep(1.1)   # Nominatim 限速，成功失敗都要等

    if not arr:
        if arr is not None:
            bump("osm_miss")
        return None
    try:
        lat, lng = round(float(arr[0]["lat"]), 6), round(float(arr[0]["lon"]), 6)
    except (KeyError, IndexError, TypeError, ValueError):
        bump("osm_error")
        return None
    if not in_bbox(lat, lng):
        bump("osm_out_of_range")
        return None
    full = arr[0].get("display_name", "")
    if not pref_gate(full, allowed_prefs):
        bump("osm_pref_rejected")
        return None
    conf = name_confidence(query, full.split(",")[0])
    if not conf:
        bump("osm_name_rejected")
        return None
    bump("osm_hit" if conf == "strong" else "osm_hit_weak")
    return (lat, lng, conf)


def geocode_photon(query, allowed_prefs=None):
    """
    Photon（komoot 提供的 OSM 搜尋）。**與 Nominatim 是同一份 OpenStreetMap 資料，
    差別在搜尋方式**：Nominatim 是地址解析器，餵它店名常常整個查不到；Photon 走全文檢索
    且容錯，所以「西武渋谷店」找得到「西武渋谷店モヴィーダ館」、「ATELIER MUJI GINZA」
    找得到「Muji Hotel」。實測 14 個 Nominatim 查不到的場地，Photon 多救回 3 個且零誤判。

    **排在 Nominatim 之後而不是之前**：這樣既有查得到的活動結果完全不變，只有原本
    查不到的才會拿到新答案，符合「重查只會變好不會變差」（見 resolve_coords）。

    官方條款：可用於自己的專案，但「請公平使用，過量會被限流」，且**不保證可用性**。
    故任何失敗都靜默退回，絕不讓它中斷流程——查不到就回到原本的退回鏈。

    ⚠ 它會犯與 Nominatim 一樣的跨縣同名錯誤：實測查「佐久山運動公園」（栃木）
    回長野縣的「佐久総合運動公園」。所以 pref_gate 與 name_confidence 一道都不能少。
    """
    lat_min, lng_min, lat_max, lng_max = GEO_BBOX
    url = ("https://photon.komoot.io/api/?limit=1&lang=default"
           f"&bbox={lng_min},{lat_min},{lng_max},{lat_max}"
           "&q=" + urllib.parse.quote(query))
    data = None
    try:
        data = json.loads(http_get(url, headers={"User-Agent": "jp-events/2.0 (github actions)"},
                                   timeout=30))
    except (urllib.error.URLError, urllib.error.HTTPError, OSError, json.JSONDecodeError) as e:
        print(f"    [geo] Photon 查詢失敗（{query}）：{e}")
        bump("photon_error")
    finally:
        time.sleep(PHOTON_WAIT)

    if not data:
        return None
    feats = data.get("features") or []
    if not feats:
        bump("photon_miss")
        return None
    f = feats[0]
    try:
        coords = f["geometry"]["coordinates"]
        lat, lng = round(float(coords[1]), 6), round(float(coords[0]), 6)
    except (KeyError, IndexError, TypeError, ValueError):
        bump("photon_error")
        return None
    if not in_bbox(lat, lng):
        bump("photon_out_of_range")
        return None

    p = f.get("properties", {})
    # ⚠️ **國別守門，與 Nominatim 的 `countrycodes=jp` 同一個理由**（2026-08-29 加）。
    # Photon 沒有國別參數可送，但它每一筆都帶 `countrycode`。實測
    # `GOODS展`（`OSAMU GOODS展` 的切分變體）回**韓國慶州**一家叫 `Goods` 的咖啡店，
    # 而 `Goods` 完整包含在 `goods展` 裡 → `name_confidence` 判 strong、
    # `pref_gate` 認不出韓文行政區名而放行，於是活動被釘到 **952km** 外。
    if p.get("countrycode") != "JP":
        bump("photon_out_of_range")
        return None
    # **東京的回傳沒有 state 欄位**（縣名被放在 city，例：city=東京都、district=渋谷区），
    # 故把幾個行政層級全部串起來再給守門，只看 state 會讓東京的活動整批漏擋。
    where = " ".join(str(p.get(k, "")) for k in ("state", "county", "city", "district"))
    if not pref_gate(where, allowed_prefs):
        bump("photon_pref_rejected")
        return None
    # **只採用 strong，不收 weak**——這點與 Nominatim 刻意不同。
    # weak（文字系統不同）對 Nominatim 是合理的：它是地址解析器，查不到就回空，
    # 所以回得出東西時多半真的是同一個地點的另一種寫法。Photon 是全文檢索＋容錯，
    # **它一定會給你「最像的那個」**，於是 weak 常常只是碰巧字面沾邊。
    # 實測「ＣＲＥＶＩＡ ＢＡＳＥ Tokyo」（全形）判 weak，回到 38.5km 外的東京西部；
    # 同一場地的半形寫法判 strong，回到正確的文京區。收 weak 會比退回市中心更差。
    conf = name_confidence(query, str(p.get("name", "")))
    if conf != "strong":
        bump("photon_name_rejected")
        return None
    bump("photon_hit")
    return (lat, lng, "strong")


def geocode(venue_ja, venue, area):
    """
    依序嘗試多種寫法查座標，任一段命中就停。回傳 (lat, lng, 段位) 或 None。

    段位順序的理由：日文原名最可靠（地圖資料庫收的就是日文名）；查不到再加上真實
    行政區名消歧義；最後才賭繁中名（中日同形的場地如「太田記念美術館」仍可能命中）。
    絕不把 area 原樣丟進查詢——「東京23區」「鎌倉湘南」是本專案的分類桶，不是地名，
    加進去只會讓原本查得到的場地變成查不到。
    """
    # 全國連鎖／多店舖／泛用說法：整段跳過不查。查到的必然是其中一家，比查不到更誤導
    if is_multi_site(venue_ja or venue):
        bump("skip_multi_site")
        return None

    attempts = []
    adm = AREA_ADMIN.get(area, "")
    allowed = AREA_PREF_OK.get(area)   # 縣別守門用，見 pref_gate
    if venue_ja:
        attempts.append(("ja", venue_ja))
        # 換個寫法（全形→半形／舊字體→新字體／英數與日文間補空白）。排在原名之後，
        # 既有查得到的完全不受影響；它比 simplify_venue 保守（只換寫法不砍字），故排在它前面
        norm_ja = normalize_venue(venue_ja)
        if norm_ja:
            attempts.append(("ja正規化", norm_ja))
        simple_ja = simplify_venue(venue_ja)
        if simple_ja:
            attempts.append(("ja簡化", simple_ja))
        # 切分寫法：斜線／並列／剝括號。整串查不到的場地多半敗在這裡（見 venue_variants）
        variants = venue_variants(venue_ja)
        for v in variants:
            # ⚠️ **光禿禿的品牌名不單獨查**（見 branch_only）：查到的必然是同品牌的
            # 另一家分店，而名稱包含 ＋ 同縣讓兩道守門都攔不住。它仍然保留在
            # 「分店變體＋行政區」那個段位裡（排在最後），所以第一百四十四筆修好的
            # `東武百貨店 池袋店` 那條路一個字都沒變。
            if branch_only(venue_ja, v):
                bump("skip_branch_only")
                continue
            attempts.append(("ja切分", v))
        # 市町村名比 AREA_ADMIN 的縣名更能消歧義，且「北關東」的 AREA_ADMIN 是空的，
        # 對三縣完全沒有這一段——正好由此補上
        base = simple_ja or venue_ja
        # ⚠️ 這裡要的只有「名字」，故走 city_name_of：撞名的市町村（府中市＝東京／廣島）
        # 兩邊寫進查詢字串的都是同樣三個字，讓它因為撞名而回 None 只會靜默少一個段位
        city_name = city_name_of(venue_ja)
        if city_name and city_name not in base:
            attempts.append(("ja+市町村", base + " " + city_name))
        if adm:
            attempts.append(("ja+行政區", (simple_ja or venue_ja) + " " + adm))
    if venue and venue != venue_ja:
        attempts.append(("zh", venue))
        simple_zh = simplify_venue(venue)
        if simple_zh:
            attempts.append(("zh簡化", simple_zh))

    # 分店後綴剝掉之後**再加行政區**。這個組合原本永遠不會被組出來：切分變體只會被
    # 光禿禿地查一次，而行政區只跟原名／簡化名組合，兩件事湊不到一起。
    # 實測「東武百貨店 池袋店」六種寫法**只有「東武百貨店 東京都」查得到**
    # （35.7298/139.7103，正是池袋那家）；其餘五種全部落空，於是只能採信 AI 給的
    # 佔位座標 35.0/139.0——那個點在駿河灣海上，而 geo="ai" 在前端是**實心圖釘**。
    # ⚠️ **排在所有段位最後**，所以既有查得到的場地一律不受影響（改前後全站實測
    # 只有那 1 筆行為改變）。作用範圍由 branch_trimmed 收緊，理由見該函式。
    if venue_ja and adm:
        for v in variants:
            if branch_trimmed(venue_ja, v):
                attempts.append(("ja分店+行政區", v + " " + adm))

    # ⚠️⚠️ **兩輪：Nominatim（與 Google）先掃完所有寫法，Photon 才上場。**
    # 根因是**搶答**，不是 Photon 判得太鬆：`成田ゆめ牧場` 的正解一直都在後面的段位
    # （`成田ゆめ牧場 千葉県` Nominatim 回的是牧場本體），但第一段就被 Photon 用
    # 「成田市幸町的直營冰淇淋店」答掉了——**名字一模一樣**，`name_confidence` 與
    # `pref_gate` 兩道都攔不住，於是活動釘在 14km 外的市區而且是 precise。
    # 這是 2026-08-28「含括號的字串不給 Photon 回答」那條的推廣：Photon 是全文檢索、
    # **一定會給你最像的那個**，所以它適合當補位，不適合跟 Nominatim 搶同一個位置。
    # ⚠️ **不是把 Photon 關掉**：第一輪整輪查無時它照樣上場（它救回過場地，見 3c）。
    # ⚠️ **總查詢次數不會變多**（每個寫法各問兩家一次），只是順序換了；
    #    代價是「原本 Photon 在第一段就命中」的那些場地，現在要先跑完整輪 Nominatim。
    for photon_round in (False, True):
        for stage, query in attempts:
            # ⚠️ **鍵要帶上 `allowed`**，理由見 GEO_CACHE 的說明：`pref_gate` 依桶而定，
            # 而命中快取這條路不會再跑一次守門，共用等於讓別的桶替這個桶做了決定。
            # ⚠️ **也要帶上是哪一輪**：兩輪問的是不同的服務，共用一個鍵的話，
            # 第一輪存下的「Nominatim 查無」會讓第二輪整個跳過，**Photon 從此永遠不會被問到**。
            key = (query, allowed, photon_round)
            if key in GEO_CACHE:
                cached = GEO_CACHE[key]
                if cached:
                    bump("cache_hit")
                    return (cached[0], cached[1], stage, cached[2])
                continue
            if photon_round:
                # ⚠️ **含括號的字串不給 Photon 回答**（2026-08-28）。Photon 是全文檢索、
                # **一定會給你「最像的那個」**，而括號裡的別名讓查詢字串變成「兩個名字的合體」，
                # 字元重疊率因此特別容易衝高，最容易配到把好幾個地名串在一起的合併物件。
                # 實測「下鴨神社(賀茂御祖神社)」：Nominatim 查無 → Photon 回右京區一個叫
                # 「賀茂下上 賀茂御祖神社(下鴨神社)賀茂別雷神社(上賀茂神社)」的物件
                # （世界遺產「古都京都の文化財」把好幾座神社收在同一個 OSM 名字裡），
                # **差 5.36km 而兩道守門都攔不住**——`pref_gate` 是縣級的（同在京都府）、
                # `name_confidence` 看到高字元重疊判 strong。典型的「自信的錯誤」。
                # ⚠️ **它一次機會都不會少**——全站 53 個含括號的場地，只有 1 個在整條查詢鏈裡
                # 沒有去括號版本（`SUBWAY (サブウェイ) 全國`，而它被 is_multi_site 整段跳過、
                # 本來就不查）。其餘 52 個後面一定還有一個乾淨字串輪到 Photon。
                if _PAREN_RE.search(query):
                    continue
                result = geocode_photon(query, allowed)
            else:
                result = geocode_google(query, allowed) if GOOGLE_ENABLED else None
                if result is None:
                    result = geocode_osm(query, allowed)
            GEO_CACHE[key] = result
            if result:
                bump("stage_" + stage)
                return (result[0], result[1], stage, result[2])
    return None


def geocode_city(city, pref):
    """
    查市町村中心點。加縣名消歧義（日本有大量同名市町村，例如栃木「小山市」與靜岡「小山町」）。
    走與場地查詢完全相同的把關與快取，不給任何豁免。
    """
    query = city + " " + pref
    # ⚠️ 鍵刻意維持兩元組：這裡是「一個查詢問完三家」的完整鏈，不分輪，
    # 與 geocode 的三元組鍵天生不會相撞（形狀不同），也就不會互相污染。
    key = (query, (pref,))
    if key in GEO_CACHE:
        cached = GEO_CACHE[key]
        return (cached[0], cached[1]) if cached else None
    result = geocode_google(query, (pref,)) if GOOGLE_ENABLED else None
    if result is None:
        result = geocode_osm(query, (pref,))
    if result is None:
        result = geocode_photon(query, (pref,))
    GEO_CACHE[key] = result
    return (result[0], result[1]) if result else None


def fallback_center(ev):
    """
    查不到座標時的退回鏈：市町村中心 → 縣中心 → 地區中心。回傳 (lat, lng)。

    舊版只有最後一段，於是「北關東」桶（橫跨三縣）的活動全部退到宇都宮，群馬的活動
    誤差可達 117km。多出來的兩段都只是把同一個「概略位置」講得更精確一點，
    **geo 標記維持 area 不變**，前端行為完全不受影響。

    市町村中心不可能指到別的城市（市中心必定落在該市內），所以這兩段沒有「查到錯地點」
    的風險——那是切分查詢才有的問題，由 name_confidence 負責。
    """
    venue = ev.get("venue_ja") or ev.get("venue") or ""
    allowed = AREA_PREF_OK.get(ev.get("area", ""))
    hit = city_of(venue, allowed)
    # 認出的市町村若不屬於這個地區桶該有的縣，代表撞到同名地名，整個丟掉往下退
    if hit and allowed and hit[1] not in allowed:
        bump("fallback_city_rejected")
        hit = None
    # 場地名認不出市町村時，才問「這個來源在報導哪個市」（單位 T-8，2026-09-06）。
    # ⚠️ **順序不可對調**：來源只說得出「這個網站在報導哪個市」，而活動可能辦在鄰市，
    # 場地名認出來的一定更準。⚠️ 它照樣要過白名單（同上面那道，猜錯＝把活動精準地
    # 畫到另一座城市，地雷 #3）。
    from_source = False
    if not hit:
        src_city = SOURCE_CITY.get(ev.get("source", ""))
        if src_city and allowed and src_city[1] not in allowed:
            bump("fallback_city_rejected")
        elif src_city:
            hit, from_source = src_city, True
    if hit:
        coord = geocode_city(hit[0], hit[1])
        if coord:
            bump("fallback_city_src" if from_source else "fallback_city")
            return coord
    # 縣級：場地名認不出市町村時（「上毛三山」「中心市街地」這種），
    # 依序用 場地名裡的縣名 → 市町村所屬縣 → 來源所屬縣。
    # 北關東那 17 個來源全部自帶縣別，所以這一段對該桶的涵蓋率是 100%。
    # ⚠️⚠️ **要逐個試，不可以「取第一個非空的，不合白名單就整個放棄」**（2026-09-06 修）：
    # 場地名寫「愛知県・滋賀県・奈良県」時 `pref_of` 回愛知県，而桶是關西周邊（不收愛知）
    # ——舊寫法就此把 pref 設成 None、**連來源自帶的滋賀県都不再問**，直接掉到最粗的
    # 地區中心。同 `fallback_city_rejected` 那道的精神：**丟掉的是這個候選，不是整條鏈。**
    for pref in (pref_of(venue), hit[1] if hit else None, SOURCE_PREF.get(ev.get("source", ""))):
        if not pref or (allowed and pref not in allowed):
            continue
        if pref in PREF_CENTER:
            bump("fallback_pref")
            return PREF_CENTER[pref]
    bump("fallback_area")
    return AREA_CENTER.get(ev.get("area", "其他"), AREA_CENTER["其他"])


def needs_strict_recheck(ev):
    """
    這筆的 `precise` 是不是舊的寬鬆規則蓋的章，必須重新驗證？

    GEO_VERSION 9 把「純英文名稱」的比對從**字元**改成**單字**（見 `_latin_confidence`），
    這是本專案第一次把判定改**嚴**，所以也是第一次需要重驗已經 precise 的資料。

    **範圍刻意收到最窄**：只有場地名是純英文的才重驗（全站 16 筆），
    因為新規則只在那條路上生效。其餘 515 筆 precise 一律不動——
    無謂的重查除了耗掉 Nominatim 的限速額度，還多一次結果變動的機會。

    **GEO_VERSION 11（2026-08-29）新增第二種：座標根本不在日本。**
    國別守門（Nominatim 的 `countrycodes=jp`、Photon 的 `countrycode`）只管**新查詢**，
    而已經蓋了 `precise` 的那兩筆會一路沿用到過期。
    ⚠️ **這一條非有不可**：`中心市街地` 這次會被 `is_multi_site` 擋在門外
    （3c 把它加進 `VAGUE_SEGMENTS`），於是 `geocode` 回 None、走進保底，
    而保底看到 previous 是 `precise` 就照樣沿用——**修了三道守門，那顆圖釘還在原地**。

    ⚠️⚠️ **這個判準在 26 桶之後只剩粗篩的價值（單位 T-6，2026-09-06 拉到 600km）。**
    當初 200km 是量出來的：那時全站最遠的日本場地只有 97.0km，而要抓的兩筆是
    586.7km（韓國慶州）與 1182.3km（中國黑龍江），中間空了六倍。
    **開了沖繩與北海道之後那個空隙沒了**——西表島 440.2km、小浜島 425.5km、
    別海町 307.6km 全部是**合法場地**，卻每輪被判「不在日本」而白重查一次。
    而反方向同樣失守：**釜山離福岡縣廳只有約 210km**，任何門檻都同時誤殺離島、
    漏掉近的國外座標。**這不是調數字的問題，是判準本身失效了。**

    所以它現在只負責「離譜到不可能是日本」那一段（600km 以上），
    **真正在做這件事的是兩道別的守門**：
      ① 新查詢的國別過濾（Nominatim `countrycodes=jp`／Photon `countrycode`，地雷 #3h）
      ② `reverify_coords()` 每輪拿国土地理院反查 120 筆（單位 T-4）——**那才是權威判準**，
         它問的是「這個座標實際落在哪一縣」，與距離無關。
    ⚠️ 門檻寬一點的代價只是「多重驗幾筆」（幾秒鐘），窄一點的代價是「誤殺離島、
    每輪白重查」，**失敗方向因此偏寬**。
    """
    if ev.get("geo") != "precise" or ev.get("geo_v") == GEO_VERSION:
        return False
    if far_from_japan(ev):
        return True
    name = _strip_generic(ev.get("venue_ja") or "")
    return bool(name) and _script(name) == "latin"


# 離最近的都道府縣中心超過這麼遠，就當成「這個座標離譜到不可能是日本」。
# ⚠️ **600 是量出來的下限，不是隨手放寬**（2026-09-06，單位 T-6）：全站 1604 筆
# 有座標的活動，最遠的**合法**場地是西表島 440.2km、其次小浜島 425.5km、別海町 307.6km
# （八重山群島離那霸就有 400km 以上），而已知要抓的是 586.7km 與 1182.3km。
# ⚠️⚠️ **不要因為「600 離 587 只差 13km」就把它調回去**——587 那筆（韓國慶州）
# 現在由國別過濾擋在新查詢那一關，這裡只是掃既有資料的粗篩。真正的守門見
# needs_strict_recheck 的說明與 reverify_coords（T-4）。
FAR_FROM_JAPAN_KM = 600


def far_from_japan(ev):
    """座標離最近的都道府縣中心太遠＝多半根本不在日本（國別守門上線前留下的舊資料）。"""
    if not ev.get("lat") or not PREF_CENTER:
        return False
    here = (ev["lat"], ev["lng"])
    return min(haversine_km(here, c) for c in PREF_CENTER.values()) > FAR_FROM_JAPAN_KM


def reverse_pref(lat, lng):
    """
    問国土地理院「這個座標實際落在哪個都道府縣」。回 `(ok, 縣名)`。

    ⚠️⚠️ **三態，不可以壓成兩態**（同 `gsi_search`／`osm_poi_search` 那條
    「查詢失敗 ≠ 查無」）：
      (True,  "東京都") 反查成功，就在這一縣
      (True,  None)     反查成功但**回空**——境外或遠洋，實測韓國慶州與日本海上都是 `{}`
      (False, None)     **查詢失敗**（逾時、HTTP 錯誤、格式不認得）。這種一律不當成證據，
                        也不更新 `geo_rv`；下一輪本身就是重試。

    ⚠️ **它只能判「屬於哪一縣」，不能判「在不在陸地上」**：實測駿河灣海面上的
    `(35.0, 139.0)`（那個著名的 AI 佔位座標）回的是 `muniCd 22222`＝**静岡県牧之原市**。
    近岸海域會被算給最近的市町村，所以「在海上」這件事要靠別的守門，不是這一支。
    """
    url = f"{REVERIFY_URL}?lat={lat}&lon={lng}"
    try:
        raw = http_get(url, headers={"User-Agent": "jp-events/2.0 (github actions)"}, timeout=30)
    except Exception as e:
        bump("reverify_error")
        return (False, None)
    try:
        data = json.loads(raw)
    except Exception:
        bump("reverify_error")
        return (False, None)
    res = data.get("results")
    if not res or not isinstance(res, dict):
        return (True, None)          # 境外／遠洋
    code = str(res.get("muniCd") or "").strip()
    if len(code) < 2:
        return (True, None)
    pref = PREF_BY_CODE.get(code[:2].zfill(2))
    if not pref:
        bump("reverify_error")       # 代碼認不得＝我們的表過期了，不是資料錯
        return (False, None)
    return (True, pref)


# 反查回空時，往周圍探這幾圈（公里）。⚠️ **2.0 是量出來的下限，不是挑的**（單位 T-7）：
# 荒尾干潟（有明海的潮間帶）在 1.0km 四點全空、2.0km 才命中熊本県——退潮時泥灘綿延數公里，
# 而那正是這道探測要救的那一類場地。第二圈 4.0 留給更寬的干潟與外突的碼頭。
# ⚠️ **上限不必再往上加**：實測韓國慶州與日本海遠洋在 2／3／5km 全部是空的，
# 也就是「境外」與「海岸線」在這個尺度上分得開——**而距離門檻分不開**
# （T-4 當初量到：該降級的大山崎 16.1km vs 不該降級的多摩川河川敷 16.3km）。
LAND_PROBE_KM = (2.0, 4.0)


def nearby_land_pref(lat, lng, allowed):
    """反查回空時，問「周圍有沒有陸地」。回 `(ok, 縣名)`，三態同 `reverse_pref`。

    **它修的是 T-4 的一個已知代價**（單位 T-7）：`reverse_pref` 對水域一律回空，
    而**海岸線、碼頭、河川敷、干潟上的座標完全可以是對的**——`横浜港(新港ふ頭、大さん橋)`
    就在碼頭外的海面上，`北谷町サンセットビーチ`、`荒尾干潟` 本來就在海陸交界。
    T-4 當時選擇「回空一律降級」，因為**距離門檻分辨不出海岸與境外**
    （該降級的大山崎 16.1km vs 不該降級的多摩川河川敷 16.3km），
    而失敗方向偏向誤降級是安全的。⚠️ **但開了沖繩與九州之後這種場地只會愈來愈多。**

    ⚠️⚠️ **這道探測「不是放寬」，因為命中的縣照樣要過 `AREA_PREF_OK`。**
    「富山的活動座標掉在沖繩海面」那筆會探到 `沖縄県`、不在北陸甲信越的白名單裡，
    **照樣降級**——它分開的只有「日本近岸」與「境外／遠洋」，不是「對」與「錯」。

    ⚠️ **整輪都查詢失敗要回 `(False, None)`**，不可以壓成「確認境外」：
    那會讓一次 GSI 抽風把一筆好座標降級成概略位置，而畫面上只是「位置變得不太準」
    （同 `reverse_pref` 三態不可壓成兩態的理由）。

    成本：只有「原點回空」的那幾筆才會走到這裡（2026-08-29 全站 799 筆裡只有 2 筆），
    最壞 8 次查詢約 9 秒，而整輪本來就有 `REVERIFY_BUDGET_SEC` 這道閘。
    """
    from math import radians, cos
    if not allowed:
        return (True, None)
    seen = None
    err = tried = 0
    for km in LAND_PROBE_KM:
        dlat = km / 111.0
        dlng = km / (111.0 * max(0.2, abs(cos(radians(lat)))))
        for a, b in ((lat + dlat, lng), (lat - dlat, lng), (lat, lng + dlng), (lat, lng - dlng)):
            time.sleep(REVERIFY_WAIT)
            tried += 1
            ok, pref = reverse_pref(a, b)
            if not ok:
                err += 1
                continue
            if pref and pref in allowed:
                bump("reverify_coast_pass")
                return (True, pref)
            if pref and not seen:
                seen = pref          # 命中陸地但縣別不合：留著讓日誌講得出落在哪一縣
        if seen:
            break                    # 已經知道是哪一縣了，不必再探外圈
    if err == tried:
        return (False, None)         # 整輪都沒問到＝不是證據
    if seen:
        return (True, seen)
    bump("reverify_offshore")
    return (True, None)


def reverify_coords(merged):
    """
    **`precise` 從來沒有被複驗過**，這一支就是補這件事（單位 T-4，地雷 #3j）。

    `can_reuse_coords` 對 `precise` 一律沿用，而 `main()` 連沿用的紀錄也會蓋上當前的
    `geo_v`——所以**一筆 precise 的 geo_v 永遠等於當前版本，看不出座標是什麼時候算的**，
    而站上原本沒有任何機制會回頭問「這個座標到底在不在對的縣」。
    2026-08-29 一次性稽核 693 筆，**11 筆落在該地區桶不接受的縣，最遠 97.6km**
    （`宝徳寺` 釘在東京港區）——那次是手動清掉的，而計畫書自己寫了
    「清理不等於修好，只要哪天再有一筆 precise 算錯，它一樣會永遠留著」。

    做法：每輪挑 `REVERIFY_PER_RUN` 筆「最久沒驗過的」，拿 GSI 反查問縣別，
    不合 `AREA_PREF_OK` 就**降級成 `geo="area"` 並改用退回鏈的座標**。

    ⚠️⚠️ **回空（境外／遠洋）也一律降級，這是拿真實資料驗過才定的。**
    第一版加了「近岸水域放行」的例外，因為 `横浜港(新港ふ頭、大さん橋)` 的座標
    就在碼頭外的海面上、反查回空，而它**完全是對的**。但全站 799 筆實測之後
    那個例外站不住：**該降級的 `大山崎` 離桶內縣廳 16.1km、不該降級的 `多摩川河川敷`
    16.3km——距離門檻分辨不出來**。而回空的只有 2 筆（横浜港、把澀谷猜到東京灣的
    `渋谷モディ7F`），影響極小；誤降級的代價是「對的變成概略位置」（横浜港退到
    神奈川縣廳，離大棧橋只有 1～2km），漏降級的代價是 32km 的實心圖釘。
    **失敗方向因此偏向誤降級**（同地雷 #3「寧可把對的標成概略，不要把錯的標成精確」）。

    ⚠️ **降級而不是「清掉座標讓它重算」**：重算很可能得到同一個錯答案（除非程式修過），
    那會變成每 7 天清一次、重算一次的循環。降級之後前端是半透明＋「概略位置」，
    **失敗方向安全**——就算反查本身錯了，代價也只是「對的被標成概略」，不會指到錯的地方。
    ⚠️ 代價要知道：**降級之後不會自己變回來**，程式哪天修好要靠 `GEO_VERSION` +1。

    ⚠️ **`geo_rv`（最後一次通過的日期）必須落地**，否則報表只會出現這一次、
    之後永遠是空的，看起來像這條路沒再生效過（同 `build_places.py` 的 `geo_src`）。
    它在 `main()` 裡**跟著座標一起沿用**：座標沒變，之前驗過的結果就仍然有效；
    走重查那條路的天生沒有 `geo_rv`，於是自動排在佇列最前面。
    """
    cand = [ev for ev in merged
            if ev.get("geo") in ("precise", "uncertain", "ai")
            and isinstance(ev.get("lat"), (int, float))
            and AREA_PREF_OK.get(ev.get("area", ""))]
    # 沒驗過的排最前面（`geo_rv` 空字串字典序最小），其餘按上次驗證日由舊到新
    cand.sort(key=lambda e: e.get("geo_rv") or "")
    queue = cand[:REVERIFY_PER_RUN]
    if not queue:
        return
    t0 = time.time()
    checked = passed = demoted = 0
    for ev in queue:
        if time.time() - t0 > REVERIFY_BUDGET_SEC:
            bump("reverify_budget_stop")
            break
        ok, pref = reverse_pref(ev["lat"], ev["lng"])
        checked += 1
        if not ok:
            continue                      # 查詢失敗：不是證據，也不更新 geo_rv
        allowed = AREA_PREF_OK.get(ev.get("area", ""))
        if not pref:
            # 回空＝境外或遠洋……**也可能是碼頭、河川敷、干潟上的正確座標**（單位 T-7）。
            # 往周圍探一圈分開這兩件事；探到的縣照樣要過下面那道白名單。
            ok, pref = nearby_land_pref(ev["lat"], ev["lng"], allowed)
            if not ok:
                continue                  # 探測整輪都查詢失敗：同樣不是證據
        if pref and pref in allowed:
            ev["geo_rv"] = TODAY.isoformat()
            passed += 1
            bump("reverify_pass")
        else:
            where = pref or "境外或遠洋"
            print(f"  [geo!] 座標落在 {where}，與地區桶「{ev.get('area')}」不合 → 降級成概略位置："
                  f"{ev.get('venue_ja') or ev.get('venue')}（{ev['lat']},{ev['lng']}）")
            ev["lat"], ev["lng"] = fallback_center(ev)
            ev["geo"] = "area"
            ev["geo_v"] = GEO_VERSION
            ev["geo_rv"] = TODAY.isoformat()
            demoted += 1
            bump("reverify_demoted")
        time.sleep(REVERIFY_WAIT)
    never = sum(1 for e in cand if not e.get("geo_rv"))
    print(f"[geo] 反查複驗 {checked} 筆（母體 {len(cand)}，還沒驗過的 {never}）→ "
          f"通過 {passed}／降級 {demoted}／查詢失敗 {GEO_STATS.get('reverify_error', 0)}")
    # 單位 T-7：海岸線探測有沒有真的在做事。⚠️ 同 T-1 的教訓——**沒有日誌的守門，
    # 等於不知道它還活著**，而這一道平常一輪只會遇到一兩筆，靜悄悄地壞掉不會有人發現。
    # 只在真的探過時才印；前綴 `[geo]` 不在公開摘要的 grep 白名單裡（地雷 #19 第 2 點）。
    if GEO_STATS.get("reverify_coast_pass") or GEO_STATS.get("reverify_offshore"):
        print(f"[geo] 反查回空 → 周圍探到陸地而放行 {GEO_STATS.get('reverify_coast_pass', 0)} 筆"
              f"／確認境外或遠洋 {GEO_STATS.get('reverify_offshore', 0)} 筆")


def can_reuse_coords(ev):
    """
    既有活動的座標可否直接沿用，不必重查。

    能沿用就沿用是為了省時（Nominatim 限速 1 req/s），但**尚未精確定位、且是用舊版
    查詢邏輯算出來的，必須重查**——否則改良查詢邏輯的效果只會套用在新活動上，
    既有活動會一路沿用舊座標直到過期，等於改了等於沒改。

    已精確定位的原則上沿用（查詢邏輯歷來只有越放越寬，重查不會更好），
    **例外是 `needs_strict_recheck`**：判定改嚴的那一次，舊的章正是要重驗的對象。
    """
    if not ev.get("id") or not ev.get("lat"):
        return False
    geo = ev.get("geo")
    if geo == "precise":
        return not needs_strict_recheck(ev)
    return geo in ("uncertain", "ai", "area") and ev.get("geo_v") == GEO_VERSION


def previous_still_ok(ev, previous):
    """保底沿用之前，先讓 previous 的座標**重新過一次現在的守門**。

    ⚠️ **沒有這道，把守門改嚴等於白改**（同地雷 #3f 的 `trust_previous`，那是同一個坑
    的另一半）。`resolve_coords` 的保底是「查不到就沿用上一次」，而**上一次那個值
    正是被新規則擋下來的東西**——`parse_latlng` 剛剛拒絕了 AI 給的座標，
    走到保底又把同一組數字原封不動填回去，**連 `geo` 都保住**。
    症狀是：重查照跑、統計照增、`ai_far_rejected` 也照樣 +1，
    **結果零改變而且沒有任何錯誤訊息**。

    只驗 `ai`：`precise`／`uncertain` 是地圖服務查回來的、當初就過了
    `pref_gate` 與 `name_confidence` 兩道，不在這次收嚴的範圍內
    （要重驗那些走的是 `needs_strict_recheck`，範圍刻意收得更窄）。
    """
    if previous.get("geo") != "ai":
        return True
    center = AREA_CENTER.get(ev.get("area", ""))
    if not center:
        return True
    if haversine_km((previous["lat"], previous["lng"]), center) <= ai_max_km(ev.get("area", "")):
        return True
    bump("previous_ai_rejected")
    return False


def resolve_coords(ev, previous=None, trust_previous=True):
    """
    決定最終座標，寫入 lat/lng/geo 並移除暫存欄位。
    geo：precise（查到且可信）/ uncertain（查到但與 AI 座標矛盾）/ ai（只有 AI）/ area（退回地區中心）

    `previous` 是這筆活動先前的紀錄（重查時才有）。**重查絕不能讓結果變差**：
    沿用進來的活動早已被清掉 ai_lat/ai_lng，若查不到又沒有 previous 可退，
    原本 AI 猜的（通常相當接近）就會被換成地區中心點，反而退步好幾公里。

    ⚠️ **`trust_previous=False` 是 `needs_strict_recheck` 專用的**，少了它整個重驗會白做：
    那些活動的 previous 就是我們判定不可信的那個座標，若照常保底，新規則擋下來之後
    又會原封不動把錯座標填回去、連 `precise` 都保住——**重查照跑、統計照增、結果零改變**，
    而且沒有任何錯誤訊息。
    """
    ai = None
    if ev.get("ai_lat") and ev.get("ai_lng"):
        ai = (ev["ai_lat"], ev["ai_lng"])
    found = geocode(ev.get("venue_ja", ""), ev.get("venue", ""), ev.get("area", ""))

    if found:
        coord = (found[0], found[1])
        # 兩種降級情形都標 uncertain，前端會顯示成概略位置而非精確位置：
        #   1. 名稱只能弱比對（文字系統不同，無法確認是同一個地方）
        #   2. 與 AI 給的座標差太遠，代表其中一個弄錯了
        if found[3] == "weak" or (ai and haversine_km(coord, ai) >= COORD_AGREE_KM):
            tag = "uncertain"
        else:
            tag = "precise"
        chosen = coord
    elif ai:
        chosen, tag = ai, "ai"
    elif (trust_previous and previous and previous.get("lat")
          and previous.get("geo") in ("precise", "uncertain", "ai")
          and previous_still_ok(ev, previous)):
        chosen, tag = (previous["lat"], previous["lng"]), previous["geo"]
        bump("kept_previous")
    else:
        chosen, tag = fallback_center(ev), "area"

    ev["lat"], ev["lng"], ev["geo"], ev["geo_v"] = chosen[0], chosen[1], tag, GEO_VERSION
    bump("geo_" + tag)
    ev.pop("ai_lat", None)
    ev.pop("ai_lng", None)
    return ev


