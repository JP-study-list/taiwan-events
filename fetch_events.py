# img 欄位空不空、那個欄位有值。**三道守門各自都正確，缺的是沒有人問過
# 「這張圖是不是佔位圖」。**
#
# ⚠️⚠️ **必須從檔名開頭錨定，這不是寫法偏好。** 日文羅馬字的「の」就是 no，
# 判準寫成「檔名含 no-image」時，`kimono-photo-event.jpg`（着物 photo）
# **會被誤殺**——而誤殺不可逆：那張好照片就此不見，畫面上只是變成一張文字卡片，
# 不會有任何人發現。實測四個來源的佔位圖 100% 是 `noimage_…`／`no_image_…`
# 這種開頭形式，而正常照片的 no 一定夾在句子中間。
# **寧可漏掉不可殺錯**——漏掉的代價只是維持現況（那筆不沉底）。
#
# ⚠️ 後面那個 `(?![a-z])` 只排除英文字母、刻意不排除數字：實測的四張裡
# `noImage3x2.png` 緊接著就是數字，連數字一起排除會漏掉它。
PLACEHOLDER_IMG_RE = re.compile(r"^no[-_ ]?(image|img|photo|pic)(?![a-z])", re.I)


def is_placeholder_img(url):
    """
    這個網址是不是來源站的「無圖」佔位圖。只看檔名，不打網路。

    判準刻意只有一條（檔名開頭），**不搭配「路徑在 /common/ 底下」那道**：
    實測四個網址雖然全部落在共用目錄裡，但加上它對命中結果一筆影響都沒有
    （兩種寫法命中完全相同的 4 個網址），而多一個條件就多一種漏掉的方式。
    """
    if not url:
        return False
    name = urllib.parse.urlsplit(url).path.rsplit("/", 1)[-1]
    return bool(PLACEHOLDER_IMG_RE.search(name))

