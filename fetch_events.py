def valid_date(s):
    try:
        return date.fromisoformat(str(s))
    except (ValueError, TypeError):
        return None


def clean_img_url(img):
    """
    正規化圖片網址。注意：許多圖床的尺寸參數是用來「要大圖」的，
    盲目移除反而會得到預設縮圖，因此保留原網址，
    僅將明確的縮圖標記提升為較大尺寸。
    """
    if not img.startswith("http"):
        return ""
    # 常見縮圖路徑/檔名標記 → 提升為大圖
    replacements = [
        ("/thumb/", "/"), ("/thumbs/", "/"), ("/small/", "/large/"),
        ("_thumb.", "."), ("_small.", "."), ("_s.jpg", ".jpg"),
        ("_s.png", ".png"), ("-thumbnail.", "."),
    ]
    for a, b in replacements:
        if a in img:
            img = img.replace(a, b)
    # Google 系圖床的尺寸片段（=s200 / =w300-h200）→ 放大
    img = re.sub(r"=s\d+(-c)?$", "=s1200", img)
    img = re.sub(r"=w\d+-h\d+(-[a-z]+)?$", "=w1200", img)
    return img


